-- ------------------------------------------------------------------------------------------------ 6. scheduled refresh (ingest/1)
-- The edge functions ingest-openfda-events and ingest-cfpb-complaints open an ingest/1 run (public.ingest_open_run_v1),
-- read their plan here, write through safety_ingest_apply_v1 (counted into ingest.runs by this function, never by the
-- caller) and close the run (public.ingest_finish_run_v1, then public.ingest_refresh_insights_v1).
create or replace function public.safety_ingest_plan_v1(p_source text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if p_source not in ('safety_faers_series', 'safety_maude_series', 'safety_cfpb_complaints') then
    raise exception 'unknown safety ingest source' using errcode = '22023'; end if;
  if p_source = 'safety_cfpb_complaints' then
    return jsonb_build_object('source', p_source,
      'latest_received', (select max(c.date_received) from safety.cfpb_complaints c),
      'products', (select coalesce(jsonb_agg(distinct t.label order by t.label), '[]'::jsonb)
                     from safety.cfpb_complaints c join safety.terms t on t.id = c.product_id
                    where c.date_received >= (select max(c2.date_received) - 90 from safety.cfpb_complaints c2)));
  end if;
  -- MDL groups and national totals first (the timeline), then products by rank; each with its search and stored series
  return jsonb_build_object('source', p_source, 'subjects', coalesce((
    select jsonb_agg(jsonb_build_object('id', s.id, 'search', s.search->(case when p_source = 'safety_faers_series' then 'faers' else 'maude' end),
             'series', (select coalesce(jsonb_agg(jsonb_build_object('series', m.series, 'coverage_from', to_char(m.coverage_from, 'YYYY-MM'),
                           'coverage_to', to_char(m.coverage_to, 'YYYY-MM'), 'unit', m.unit, 'method', m.method)
                           order by m.series), '[]'::jsonb)
                          from safety.series_meta m where m.subject_id = s.id
                           and m.source_id = case when p_source = 'safety_faers_series' then 'openfda_faers' else 'openfda_maude' end))
             order by case s.subject_type when 'mdl_group' then 0 when 'national' then 1 else 2 end, s.rank nulls last, s.id)
      from safety.subjects s
     where s.search ? (case when p_source = 'safety_faers_series' then 'faers' else 'maude' end)
       and exists (select 1 from safety.series_meta m where m.subject_id = s.id
                    and m.source_id = case when p_source = 'safety_faers_series' then 'openfda_faers' else 'openfda_maude' end)), '[]'::jsonb));
end $$;

create or replace function public.safety_ingest_apply_v1(p_run uuid, p_target text, p_rows jsonb, p_opts jsonb default '{}')
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_source text; v_status text; v_res jsonb;
begin
  if to_regclass('ingest.runs') is null then raise exception 'ingest/1 is not installed' using errcode = '55000'; end if;
  execute 'select source, status from ingest.runs where id = $1 for update' into v_source, v_status using p_run;
  if v_source is null then raise exception 'unknown run' using errcode = '22023'; end if;
  if v_status <> 'running' then raise exception 'run is not open' using errcode = '22023'; end if;
  if v_source not in ('safety_faers_series', 'safety_maude_series', 'safety_cfpb_complaints') then
    raise exception 'not a safety ingest source' using errcode = '22023'; end if;
  if (v_source in ('safety_faers_series', 'safety_maude_series') and p_target not in ('series', 'series_meta'))
     or (v_source = 'safety_cfpb_complaints' and p_target <> 'cfpb_complaints') then
    raise exception 'target % is not written by source %', p_target, v_source using errcode = '22023'; end if;
  v_res := public.safety_load_v1(p_target, p_rows, p_opts, jsonb_build_object('source', v_source, 'part', 'ingest', 'run_id', p_run::text));
  execute 'update ingest.runs set inserted = inserted + $2, updated = updated + $3, unchanged = unchanged + $4 where id = $1'
    using p_run, (v_res->>'inserted')::integer, (v_res->>'updated')::integer + (v_res->>'deleted')::integer, (v_res->>'unchanged')::integer;
  return v_res;
end $$;

