-- ------------------------------------------------------------------------------------------------ 3. helpers
create or replace function safety.month_of(p text) returns date
language sql immutable set search_path = '' as $$
  select case when p ~ '^[12][0-9]{3}-(0[1-9]|1[0-2])$' then to_date(p || '-01', 'YYYY-MM-DD') end
$$;

create or replace function safety.iso_date(p text) returns date
language plpgsql immutable set search_path = '' as $$
begin
  if p is null or p !~ '^[12][0-9]{3}-[01][0-9]-[0-3][0-9]$' then return null; end if;
  return p::date;
exception when others then return null;
end $$;

-- the openFDA / NHTSA style URL check: https, and never a credential parameter
create or replace function safety.url_ok(p text) returns boolean
language sql immutable set search_path = '' as $$
  select p is not null and p ~ '^https://[^\s]+$' and p !~* '[?&](api[_-]?key|apikey|access_token|token)='
$$;

-- term ids for (kind, label) pairs, inserting the missing ones
create or replace function safety.term_ids(p_kind text, p_labels text[]) returns table (label text, id integer)
language plpgsql set search_path = '' as $$
#variable_conflict use_column
begin
  insert into safety.terms (kind, label)
    select distinct p_kind, l from unnest(p_labels) l where l is not null
    on conflict (kind, label) do nothing;
  return query select t.label, t.id from safety.terms t where t.kind = p_kind and t.label = any (p_labels);
end $$;

create or replace function safety.caveat(p_source text) returns text
language sql immutable set search_path = '' as $$
  select case
    when p_source in ('openfda_faers', 'openfda_caers') then
      'Voluntary, unverified reports that list the product; a report does not establish that the product caused the event. Counts change as FDA adds, merges and revises reports; reporting rises with publicity and litigation.'
    when p_source = 'openfda_maude' then
      'Medical device reports are submitted by manufacturers, facilities and the public; a report does not establish that the device caused or contributed to the event, and counts are not incidence rates.'
    when p_source in ('openfda_enforcement', 'openfda_device_recall', 'nhtsa_recalls') then
      'Recall and enforcement records as published; a recall is not a finding of injury, and one recall event can list several products.'
    when p_source = 'nhtsa_complaints' then
      'Complaints are submitted by vehicle owners and others and are not verified by NHTSA; a complaint does not establish a defect.'
    when p_source = 'cfpb_complaints' then
      'Complaints are not verified by the CFPB; volume reflects consumer use of the system as well as company conduct.'
    when p_source = 'jpml' then
      'JPML pending-report totals; the monthly increase counts actions added to the MDL between consecutive reports (transfers and direct filings), not individual claims.'
    else 'As published by the source.'
  end
$$;

-- ------------------------------------------------------------------------------------------------ 4. loaders
-- One internal loader per target. Each validates every row first (one invalid row rolls the whole call back), refuses
-- duplicate keys inside a call, upserts by the natural key (an identical row is left untouched) and returns
-- [inserted, updated, unchanged, deleted]. Replace options delete only inside the scope the batch names.
create or replace function safety.fail(p_target text, p_problem text, p_row jsonb) returns void
language plpgsql set search_path = '' as $$
begin
  raise exception '%: % (row %)', p_target, p_problem, left(coalesce(p_row::text, ''), 300) using errcode = '22023';
end $$;

create or replace function safety.load_subjects(p_rows jsonb, p_opts jsonb) returns integer[]
language plpgsql set search_path = '' as $$
declare v_bad jsonb; v_ins integer; v_upd integer; v_n integer;
begin
  select e into v_bad from jsonb_array_elements(p_rows) e
   where (e->>'id') !~ '^[a-z][a-z0-9_]{1,20}:[A-Za-z0-9][A-Za-z0-9._-]{0,99}$'
      or coalesce(e->>'subject_type', '') not in ('product', 'device_code', 'mdl_group', 'national')
      or coalesce(e->>'kind', '') not in ('drug', 'device', 'food', 'cosmetic', 'vehicle', 'consumer_product', 'tobacco', 'all')
      or coalesce(length(e->>'label'), 0) not between 1 and 300
      or not safety.url_ok(e->>'source_url')
      or not exists (select 1 from safety.sources s where s.id = e->>'source_id')
      or (e ? 'keys' and jsonb_typeof(e->'keys') <> 'object') or (e ? 'search' and jsonb_typeof(e->'search') <> 'object')
      or (e->>'search') ~* '(api[_-]?key|apikey|access_token)'
   limit 1;
  if v_bad is not null then perform safety.fail('subjects', 'invalid subject', v_bad); end if;
  select count(*) - count(distinct e->>'id') into v_n from jsonb_array_elements(p_rows) e;
  if v_n > 0 then perform safety.fail('subjects', 'duplicate ids in one call', null); end if;
  with src as (
    select e->>'id' id, e->>'subject_type' st, e->>'kind' kind, e->>'label' label, coalesce(e->'keys', '{}') keys,
           coalesce(e->'search', '{}') search, (e->>'rank')::integer rank, (e->>'reports_total')::bigint total,
           safety.iso_date(e->>'as_of') as_of, e->>'source_id' sid, e->>'source_url' url
    from jsonb_array_elements(p_rows) e),
  up as (
    insert into safety.subjects as t (id, subject_type, kind, label, keys, search, rank, reports_total, as_of, source_id, source_url)
    select id, st, kind, label, keys, search, rank, total, as_of, sid, url from src
    on conflict (id) do update set subject_type = excluded.subject_type, kind = excluded.kind, label = excluded.label,
      keys = excluded.keys, search = excluded.search, rank = excluded.rank, reports_total = excluded.reports_total,
      as_of = excluded.as_of, source_id = excluded.source_id, source_url = excluded.source_url, updated_at = now()
    where (t.subject_type, t.kind, t.label, t.keys, t.search, t.rank, t.reports_total, t.as_of, t.source_id, t.source_url)
      is distinct from (excluded.subject_type, excluded.kind, excluded.label, excluded.keys, excluded.search, excluded.rank,
