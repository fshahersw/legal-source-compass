-- The one write entry point for builders (the lead runs scripts/safety_v2/load.py). p_meta: {"source", "part", "sha256"}.
create or replace function public.safety_load_v1(p_target text, p_rows jsonb, p_opts jsonb default '{}', p_meta jsonb default '{}')
returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v integer[]; v_id bigint;
begin
  if p_target is null or p_target not in ('subjects', 'mdl_subjects', 'series', 'series_meta', 'breakdowns', 'breakdown_meta',
      'maude_reports', 'record_subjects', 'nhtsa_complaints', 'neiss_cases', 'cfpb_monthly', 'cfpb_complaints',
      'osha_inspections', 'osha_violations', 'osha_accidents', 'open_payments') then
    raise exception 'unknown target %', left(coalesce(p_target, ''), 40) using errcode = '22023';
  end if;
  if jsonb_typeof(p_rows) is distinct from 'array' or jsonb_array_length(p_rows) = 0 or jsonb_array_length(p_rows) > 10000 then
    raise exception 'rows must be an array of 1 to 10000 rows' using errcode = '22023';
  end if;
  if exists (select 1 from jsonb_array_elements(p_rows) e where jsonb_typeof(e) <> 'object') then
    raise exception 'every row must be an object' using errcode = '22023';
  end if;
  if p_rows::text ~* '[?&](api[_-]?key|apikey|access_token)=' then
    raise exception 'rows must not carry credentials' using errcode = '22023';
  end if;
  if jsonb_typeof(coalesce(p_opts, '{}')) <> 'object' or jsonb_typeof(coalesce(p_meta, '{}')) <> 'object' then
    raise exception 'opts and meta must be objects' using errcode = '22023';
  end if;
  execute format('select safety.%I($1, $2)', 'load_' || p_target) into v using p_rows, coalesce(p_opts, '{}');
  insert into safety.loads (target, source, part, sha256, rows, inserted, updated, unchanged, deleted, run_id)
    values (p_target, left(p_meta->>'source', 60), left(p_meta->>'part', 200),
            case when p_meta->>'sha256' ~ '^[0-9a-f]{64}$' then p_meta->>'sha256' end,
            jsonb_array_length(p_rows), v[1], v[2], v[3], v[4],
            case when p_meta->>'run_id' ~ '^[0-9a-f-]{36}$' then (p_meta->>'run_id')::uuid end)
    returning id into v_id;
  return jsonb_build_object('load', v_id, 'target', p_target, 'rows', jsonb_array_length(p_rows), 'inserted', v[1],
    'updated', v[2], 'unchanged', v[3], 'deleted', v[4]);
end $$;

-- ------------------------------------------------------------------------------------------------ 5. read RPCs
-- Stored series id → the series name the product signal timeline reads (null: not part of the timeline).
create or replace function safety.public_series(p text) returns text
language sql immutable set search_path = '' as $$
  select case p
    when 'faers_reports' then 'adverse_events' when 'caers_reports' then 'adverse_events'
    when 'faers_serious' then 'adverse_events_serious' when 'faers_death' then 'adverse_events_death'
    when 'maude_reports' then 'device_reports' when 'maude_death' then 'device_reports_death'
    when 'maude_injury' then 'device_reports_injury' when 'maude_malfunction' then 'device_reports_malfunction'
    when 'enforcement_reports' then 'enforcement_reports'
    when 'device_recalls' then 'recalls' when 'nhtsa_recalls' then 'recalls'
    when 'nhtsa_complaints' then 'complaints'
  end
$$;

-- Monthly signal series for one MDL's product group (VIZ-B product signal timeline).
--   series: adverse_events | adverse_events_serious | adverse_events_death | device_reports | device_reports_death |
--           device_reports_injury | device_reports_malfunction | enforcement_reports | recalls | complaints |
--           filings | docket_entries | documents_filed
--   month 'YYYY-MM'; value: a count for that month (filings: the change in the JPML total-actions figure between two
--   consecutive monthly reports, so it can be negative after a correction); unit; source_dataset (a safety.sources id
--   or a corpus dataset id); source_url (the exact query or document); basis (why this series belongs to this MDL).
-- Months inside a stored series' coverage window that the source omits are 0 (openFDA date counts omit empty days);
-- months outside it are absent. An MDL with no product link returns only its litigation series (or nothing).
create or replace function public.product_signals_v1(p_mdl text)
returns table (series text, month text, value numeric, unit text, source_dataset text, source_url text, basis text)
language plpgsql stable security definer set search_path = '' as $$
declare v_mdl integer;
begin
  if p_mdl is null or p_mdl !~ '^[1-9][0-9]{0,4}$' then raise exception 'Invalid MDL' using errcode = '22023'; end if;
  v_mdl := p_mdl::integer;
  return query
  with links as (
    select ms.subject_id, ms.basis || ' — ' || ms.basis_note as why
      from safety.mdl_subjects ms where ms.mdl = v_mdl and ms.relation = 'mdl_group'),
  meta as (
    select l.subject_id, l.why, m.series as stored, m.unit, m.source_id, m.query_url, m.coverage_from, m.coverage_to
      from links l join safety.series_meta m on m.subject_id = l.subject_id
     where safety.public_series(m.series) is not null),
  grid as (
    select mt.*, g::date as m from meta mt
     cross join lateral generate_series(mt.coverage_from, mt.coverage_to, interval '1 month') g)
  select safety.public_series(g.stored), to_char(g.m, 'YYYY-MM'), coalesce(s.value, 0)::numeric, g.unit, g.source_id,
         g.query_url, g.why
    from grid g left join safety.series s on s.subject_id = g.subject_id and s.series = g.stored and s.month = g.m
  union all
  -- filings: JPML pending reports, total actions, month-over-month change between consecutive monthly reports
  select 'filings', h.month, (h.total - h.prev_total)::numeric, 'actions added between consecutive JPML monthly reports',
         'jpml_pending_history_mdls', h.url,
         'JPML pending-report total actions for MDL ' || v_mdl || ' (the MDL''s own record); ' || safety.caveat('jpml')
    from (select e->>'month' as month, (e->>'total')::numeric as total, e->>'source_url' as url,
                 lag((e->>'total')::numeric) over (order by e->>'month') as prev_total,
                 lag(e->>'month') over (order by e->>'month') as prev_month
            from public.corpus_records r cross join lateral jsonb_array_elements(r.item->'history'->'series') e
           where r.dataset = 'jpml_pending_history_mdls' and r.id = p_mdl
             and e->>'month' ~ '^[12][0-9]{3}-[01][0-9]$' and e->>'total' ~ '^[0-9]+$') h
   where h.prev_month is not null
     and to_date(h.prev_month || '-01', 'YYYY-MM-DD') = to_date(h.month || '-01', 'YYYY-MM-DD') - interval '1 month'
     and h.url ~ '^https://'
  union all
  -- docket entries of the MDL's master docket, by the month the entry was published
  select 'docket_entries', d.month, d.n::numeric, 'docket entries', 'mdl_docket_activity', d.url,
         'Entries of the MDL ' || v_mdl || ' master docket as listed in mdl_docket_activity (filters.mdl = ' || v_mdl || ')'
    from (select left(r.item->'cells'->>'published_at', 7) as month, count(*) as n, min(r.source_url) as url
            from public.corpus_records r
           where r.dataset = 'mdl_docket_activity' and r.filters->'mdl' ? p_mdl
             and r.item->'cells'->>'published_at' ~ '^[12][0-9]{3}-[01][0-9]-[0-3][0-9]$'
           group by 1) d
   where d.url ~ '^https://'
  order by 1, 2;
  -- court filings stored in the documents layer (documents/1), when that schema is installed
  if to_regclass('documents.documents') is not null then
    return query execute
      'select ''documents_filed''::text, to_char(d.filed_date, ''YYYY-MM''), count(*)::numeric, ''documents''::text,
              ''documents''::text, min(d.source_url),
              ''Court filings of MDL '' || $1 || '' in the documents layer (listed by '' || string_agg(distinct d.listed_by, '', '') || '')''
         from documents.documents d
        where d.mdl = $1 and d.filed_date is not null and d.source_url ~ ''^https://''
        group by 2 order by 2'
      using p_mdl;
  end if;
end $$;

