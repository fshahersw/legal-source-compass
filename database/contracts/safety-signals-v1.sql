-- Listing of subjects (products, device codes, MDL groups) with search and paging.
create or replace function public.safety_subjects_v1(p_type text default null, p_kind text default null, p_q text default null,
  p_limit integer default 50, p_offset integer default 0) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_q text; v_total integer; v_rows jsonb;
begin
  if p_limit is null or p_limit not between 1 and 200 or p_offset is null or p_offset not between 0 and 100000 then
    raise exception 'Invalid page' using errcode = '22023'; end if;
  if p_type is not null and p_type not in ('product', 'device_code', 'mdl_group', 'national') then
    raise exception 'Invalid type' using errcode = '22023'; end if;
  if p_kind is not null and p_kind !~ '^[a-z_]{2,20}$' then raise exception 'Invalid kind' using errcode = '22023'; end if;
  if p_q is not null and length(p_q) > 100 then raise exception 'Query too long' using errcode = '22023'; end if;
  v_q := nullif(lower(btrim(coalesce(p_q, ''))), '');
  with hits as (
    select s.* from safety.subjects s
     where (p_type is null or s.subject_type = p_type) and (p_kind is null or s.kind = p_kind)
       and (v_q is null or position(v_q in lower(s.label)) > 0 or position(v_q in lower(s.id)) > 0
            or position(v_q in lower(coalesce(s.keys->>'brand_names', ''))) > 0))
  select (select count(*) from hits),
         coalesce((select jsonb_agg(jsonb_build_object('id', h.id, 'subject_type', h.subject_type, 'kind', h.kind,
                     'label', h.label, 'keys', h.keys, 'rank', h.rank, 'reports_total', h.reports_total, 'as_of', h.as_of,
                     'source_id', h.source_id,
                     'mdls', (select coalesce(jsonb_agg(ms.mdl order by ms.mdl), '[]'::jsonb) from safety.mdl_subjects ms
                              where ms.subject_id = h.id))
                     order by h.rank nulls last, h.reports_total desc nulls last, h.id)
                   from (select * from hits order by rank nulls last, reports_total desc nulls last, id
                         limit p_limit offset p_offset) h), '[]'::jsonb)
    into v_total, v_rows;
  return jsonb_build_object('total', v_total, 'rows', v_rows, 'limit', p_limit, 'offset', p_offset);
end $$;

-- One subject's profile: the subject, its MDL links, every stored series (monthly points), the all-time breakdowns and
-- record counts. Series points cover the stored coverage window (omitted months are 0 inside it, see product_signals_v1).
create or replace function public.safety_subject_v1(p_id text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare s safety.subjects;
begin
  if p_id is null or p_id !~ '^[a-z][a-z0-9_]{1,20}:[A-Za-z0-9][A-Za-z0-9._-]{0,99}$' then
    raise exception 'Invalid subject' using errcode = '22023'; end if;
  select * into s from safety.subjects where id = p_id;
  if not found then return null; end if;
  return jsonb_build_object(
    'subject', jsonb_build_object('id', s.id, 'subject_type', s.subject_type, 'kind', s.kind, 'label', s.label, 'keys', s.keys,
       'search', s.search, 'rank', s.rank, 'reports_total', s.reports_total, 'as_of', s.as_of, 'source_id', s.source_id,
       'source_url', s.source_url, 'source_label', (select so.label from safety.sources so where so.id = s.source_id),
       'caveat', safety.caveat(s.source_id)),
    'mdls', coalesce((select jsonb_agg(jsonb_build_object('mdl', ms.mdl, 'relation', ms.relation, 'title', ms.title,
               'title_tokens', to_jsonb(ms.title_tokens), 'title_source_dataset', ms.title_source_dataset,
               'title_source_url', ms.title_source_url, 'basis', ms.basis, 'basis_note', ms.basis_note) order by ms.mdl)
             from safety.mdl_subjects ms where ms.subject_id = s.id), '[]'::jsonb),
    'series', coalesce((select jsonb_agg(jsonb_build_object('series', m.series, 'timeline_series', safety.public_series(m.series),
               'unit', m.unit, 'source_id', m.source_id, 'query_url', m.query_url, 'method', m.method,
               'coverage_from', to_char(m.coverage_from, 'YYYY-MM'), 'coverage_to', to_char(m.coverage_to, 'YYYY-MM'),
               'retrieved_at', m.retrieved_at, 'total', m.total, 'caveat', safety.caveat(m.source_id),
               'points', (select coalesce(jsonb_agg(jsonb_build_array(to_char(g::date, 'YYYY-MM'), coalesce(v.value, 0))
                                                     order by g), '[]'::jsonb)
                            from generate_series(m.coverage_from, m.coverage_to, interval '1 month') g
                            left join safety.series v on v.subject_id = m.subject_id and v.series = m.series and v.month = g::date))
               order by m.series)
             from safety.series_meta m where m.subject_id = s.id), '[]'::jsonb),
    'breakdowns', coalesce((select jsonb_object_agg(bm.dim, jsonb_build_object('period', bm.period, 'limit_n', bm.limit_n,
               'returned', bm.returned, 'truncated', bm.returned >= bm.limit_n, 'reports', bm.reports, 'query_url', bm.query_url,
               'retrieved_at', bm.retrieved_at,
               'rows', (select coalesce(jsonb_agg(jsonb_build_object('term', t.label, 'value', b.value, 'serious', b.serious)
                                                  order by b.value desc, t.label), '[]'::jsonb)
                          from (select * from safety.breakdowns b0 where b0.subject_id = s.id and b0.dim = bm.dim
                                  and b0.period = bm.period order by b0.value desc limit 60) b
                          join safety.terms t on t.id = b.term_id)))
             from safety.breakdown_meta bm where bm.subject_id = s.id and bm.period = 'all'), '{}'::jsonb),
    'quarters', coalesce((select jsonb_agg(distinct bm.period order by bm.period) from safety.breakdown_meta bm
               where bm.subject_id = s.id and bm.period ~ '-Q'), '[]'::jsonb),
    'records', jsonb_build_object(
       'maude', (select count(*) from safety.record_subjects r where r.subject_id = s.id and r.source = 'maude'),
       'nhtsa', (select count(*) from safety.record_subjects r where r.subject_id = s.id and r.source = 'nhtsa')));
end $$;

-- Term counts of one subject for one period (or 'all'), top first.
create or replace function public.safety_breakdown_v1(p_id text, p_dim text, p_period text default 'all', p_limit integer default 100)
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if p_id is null or p_id !~ '^[a-z][a-z0-9_]{1,20}:[A-Za-z0-9][A-Za-z0-9._-]{0,99}$' then raise exception 'Invalid subject' using errcode = '22023'; end if;
  if p_dim is null or p_dim !~ '^[a-z_]{3,30}$' then raise exception 'Invalid dimension' using errcode = '22023'; end if;
  if p_period is null or not (p_period = 'all' or p_period ~ '^[12][0-9]{3}(-Q[1-4])?$') then raise exception 'Invalid period' using errcode = '22023'; end if;
  if p_limit is null or p_limit not between 1 and 1000 then raise exception 'Invalid limit' using errcode = '22023'; end if;
  return jsonb_build_object(
    'meta', (select jsonb_build_object('limit_n', bm.limit_n, 'returned', bm.returned, 'truncated', bm.returned >= bm.limit_n,
               'reports', bm.reports, 'query_url', bm.query_url, 'retrieved_at', bm.retrieved_at)
               from safety.breakdown_meta bm where bm.subject_id = p_id and bm.dim = p_dim and bm.period = p_period),
    'rows', coalesce((select jsonb_agg(jsonb_build_object('term', t.label, 'value', b.value, 'serious', b.serious)
               order by b.value desc, t.label)
               from (select * from safety.breakdowns b0 where b0.subject_id = p_id and b0.dim = p_dim and b0.period = p_period
                      order by b0.value desc limit p_limit) b join safety.terms t on t.id = b.term_id), '[]'::jsonb));
end $$;

-- Quarter-by-term matrix (reaction or problem heatmap): the given terms (or the subject's top terms) per quarter.
create or replace function public.safety_term_quarters_v1(p_id text, p_dim text, p_terms text[] default null,
  p_from text default null, p_to text default null, p_top integer default 12) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_terms text[];
begin
  if p_id is null or p_id !~ '^[a-z][a-z0-9_]{1,20}:[A-Za-z0-9][A-Za-z0-9._-]{0,99}$' then raise exception 'Invalid subject' using errcode = '22023'; end if;
  if p_dim is null or p_dim !~ '^[a-z_]{3,30}$' then raise exception 'Invalid dimension' using errcode = '22023'; end if;
  if (p_from is not null and p_from !~ '^[12][0-9]{3}-Q[1-4]$') or (p_to is not null and p_to !~ '^[12][0-9]{3}-Q[1-4]$') then
    raise exception 'Invalid quarter' using errcode = '22023'; end if;
  if p_top is null or p_top not between 1 and 50 or cardinality(coalesce(p_terms, '{}')) > 50 then
    raise exception 'Invalid term count' using errcode = '22023'; end if;
  v_terms := coalesce(p_terms, array(
    select t.label from safety.breakdowns b join safety.terms t on t.id = b.term_id
     where b.subject_id = p_id and b.dim = p_dim and b.period = 'all' order by b.value desc, t.label limit p_top));
  return jsonb_build_object(
    'terms', to_jsonb(v_terms),
    'quarters', coalesce((select jsonb_agg(jsonb_build_object('period', bm.period, 'limit_n', bm.limit_n, 'returned', bm.returned,
                  'truncated', bm.returned >= bm.limit_n, 'reports', bm.reports, 'query_url', bm.query_url) order by bm.period)
                  from safety.breakdown_meta bm
                 where bm.subject_id = p_id and bm.dim = p_dim and bm.period ~ '-Q'
                   and (p_from is null or bm.period >= p_from) and (p_to is null or bm.period <= p_to)), '[]'::jsonb),
    'cells', coalesce((select jsonb_agg(jsonb_build_array(b.period, t.label, b.value, b.serious) order by b.period, t.label)
                  from safety.breakdowns b join safety.terms t on t.id = b.term_id
                 where b.subject_id = p_id and b.dim = p_dim and b.period ~ '-Q' and t.label = any (v_terms)
                   and (p_from is null or b.period >= p_from) and (p_to is null or b.period <= p_to)), '[]'::jsonb));
end $$;

-- The official page of one record, where the publisher has one; else the file or API it came from.
create or replace function safety.record_url(p_source text, p_id text, p_extra text default null) returns text
language sql immutable set search_path = '' as $$
  select case p_source
    when 'maude' then case when p_extra ~ '^[0-9]{1,20}$'
      then 'https://www.accessdata.fda.gov/scripts/cdrh/cfdocs/cfmaude/detail.cfm?mdrfoi__id=' || p_extra
      else 'https://open.fda.gov/apis/device/event/' end
    when 'nhtsa' then 'https://static.nhtsa.gov/odi/ffdd/cmpl/' || coalesce(p_extra, 'FLAT_CMPL.zip')
    when 'neiss' then 'https://www.cpsc.gov/cgibin/NEISSQuery/Data/Archived%20Data/' || coalesce(p_extra, '') || '/neiss' || coalesce(p_extra, '') || '.tsv'
    when 'cfpb' then 'https://www.consumerfinance.gov/data-research/consumer-complaints/search/detail/' || p_id
    when 'osha' then 'https://www.osha.gov/ords/imis/establishment.inspection_detail?id=' || p_id
    when 'osha_accidents' then 'https://www.osha.gov/ords/imis/accidentsearch.accident_detail?id=' || p_id
  end
$$;

-- Record lists. p_source: maude | nhtsa | neiss | cfpb | osha | osha_accidents. p_subject restricts maude/nhtsa to the
-- records linked to that subject (record_subjects). p_filter (all optional, exact values): {"make": "...",
-- "product": "<NEISS code>", "company": "<CFPB company as published>", "estab": "<OSHA establishment as published>",
-- "state": "XX", "event_type": "..."}. total is exact up to 10,000 (capped = true beyond).
create or replace function public.safety_records_v1(p_source text, p_subject text default null, p_q text default null,
  p_from date default null, p_to date default null, p_filter jsonb default '{}', p_limit integer default 25,
  p_offset integer default 0) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_q text; v_rows jsonb; v_total integer; c_cap constant integer := 10000; f jsonb := coalesce(p_filter, '{}');
begin
  if p_source is null or p_source not in ('maude', 'nhtsa', 'neiss', 'cfpb', 'osha', 'osha_accidents') then
    raise exception 'Invalid source' using errcode = '22023'; end if;
  if p_limit is null or p_limit not between 1 and 100 or p_offset is null or p_offset not between 0 and 5000 then
    raise exception 'Invalid page' using errcode = '22023'; end if;
  if p_subject is not null and p_subject !~ '^[a-z][a-z0-9_]{1,20}:[A-Za-z0-9][A-Za-z0-9._-]{0,99}$' then
    raise exception 'Invalid subject' using errcode = '22023'; end if;
  if p_q is not null and length(p_q) > 100 then raise exception 'Query too long' using errcode = '22023'; end if;
  if jsonb_typeof(f) <> 'object' or exists (select 1 from jsonb_each(f) kv where jsonb_typeof(kv.value) <> 'string' or length(kv.value #>> '{}') > 200) then
    raise exception 'Invalid filter' using errcode = '22023'; end if;
  if p_from is not null and p_to is not null and p_from > p_to then raise exception 'Invalid date range' using errcode = '22023'; end if;
  v_q := nullif(lower(btrim(coalesce(p_q, ''))), '');

  if p_source = 'maude' then
    with hits as (
      select r.* from safety.maude_reports r
       where (p_subject is null or exists (select 1 from safety.record_subjects x where x.subject_id = p_subject and x.source = 'maude' and x.record_id = r.report_number))
         and (p_from is null or r.date_received >= p_from) and (p_to is null or r.date_received <= p_to)
         and (f->>'event_type' is null or r.event_type = f->>'event_type')
         and (v_q is null or position(v_q in lower(coalesce(r.event_text, '') || ' ' || coalesce(r.manufacturer_narrative, '') || ' '
              || array_to_string(r.brand_names, ' ') || ' ' || array_to_string(r.device_problems, ' '))) > 0))
    select (select count(*) from (select 1 from hits limit c_cap + 1) c),
           coalesce(jsonb_agg(jsonb_build_object('id', h.report_number, 'date', h.date_received, 'event_date', h.date_of_event,
             'event_type', h.event_type, 'brand_names', to_jsonb(h.brand_names), 'manufacturers', to_jsonb(h.manufacturers),
             'product_codes', to_jsonb(h.product_codes), 'device_problems', to_jsonb(h.device_problems),
             'patient_problems', to_jsonb(h.patient_problems), 'excerpt', left(coalesce(h.event_text, ''), 400),
             'source_url', safety.record_url('maude', h.report_number, h.mdr_report_key)) order by h.date_received desc nulls last, h.report_number), '[]'::jsonb)
      into v_total, v_rows
      from (select * from hits order by date_received desc nulls last, report_number limit p_limit offset p_offset) h;
  elsif p_source = 'nhtsa' then
    with hits as (
      select c.* from safety.nhtsa_complaints c
       where (p_subject is null or exists (select 1 from safety.record_subjects x where x.subject_id = p_subject and x.source = 'nhtsa' and x.record_id = c.odino::text))
         and (p_from is null or c.received >= p_from) and (p_to is null or c.received <= p_to)
         and (f->>'make' is null or c.makes @> array[f->>'make']) and (f->>'state' is null or c.consumer_state = f->>'state')
         and (v_q is null or position(v_q in lower(coalesce(c.description, '') || ' ' || array_to_string(c.components, ' ')
              || ' ' || array_to_string(c.models, ' '))) > 0))
    select (select count(*) from (select 1 from hits limit c_cap + 1) c),
           coalesce(jsonb_agg(jsonb_build_object('id', h.odino, 'date', h.received, 'incident_date', h.incident_date,
             'manufacturer', h.manufacturer, 'items', h.items, 'crash', h.crash, 'fire', h.fire, 'injured', h.injured,
             'deaths', h.deaths, 'state', h.consumer_state, 'excerpt', left(coalesce(h.description, ''), 400),
             'source_url', safety.record_url('nhtsa', h.odino::text, case when h.received >= date '2025-01-01'
                 then 'COMPLAINTS_RECEIVED_2025-2026.zip' else 'COMPLAINTS_RECEIVED_2020-2024.zip' end))
             order by h.received desc nulls last, h.odino), '[]'::jsonb)
      into v_total, v_rows
      from (select * from hits order by received desc nulls last, odino limit p_limit offset p_offset) h;
  elsif p_source = 'neiss' then
    with hits as (
      select n.* from safety.neiss_cases n
       where (p_from is null or n.treatment_date >= p_from) and (p_to is null or n.treatment_date <= p_to)
         and (f->>'product' is null or (f->>'product' ~ '^[0-9]{1,4}$' and (f->>'product')::smallint in (n.product_1, n.product_2, n.product_3)))
         and (v_q is null or position(v_q in lower(coalesce(n.narrative, ''))) > 0))
    select (select count(*) from (select 1 from hits limit c_cap + 1) c),
           coalesce(jsonb_agg(jsonb_build_object('id', h.case_number, 'date', h.treatment_date, 'age', h.age, 'sex', h.sex,
             'products', jsonb_build_array(h.product_1, h.product_2, h.product_3), 'diagnosis', h.diagnosis, 'body_part', h.body_part,
             'disposition', h.disposition, 'weight', h.weight, 'stratum', h.stratum, 'psu', h.psu,
             'excerpt', left(coalesce(h.narrative, ''), 400), 'source_url', safety.record_url('neiss', h.case_number::text, h.file_year::text))
             order by h.treatment_date desc, h.case_number), '[]'::jsonb)
      into v_total, v_rows
      from (select * from hits order by treatment_date desc, case_number limit p_limit offset p_offset) h;
  elsif p_source = 'cfpb' then
    with hits as (
      select c.* from safety.cfpb_complaints c
       where (p_from is null or c.date_received >= p_from) and (p_to is null or c.date_received <= p_to)
         and (f->>'company' is null or c.company_id = (select t.id from safety.terms t where t.kind = 'cfpb_company' and t.label = f->>'company'))
         and (f->>'product' is null or c.product_id = (select t.id from safety.terms t where t.kind = 'cfpb_product' and t.label = f->>'product'))
         and (f->>'state' is null or c.state = f->>'state'))
    select (select count(*) from (select 1 from hits limit c_cap + 1) c),
           coalesce(jsonb_agg(jsonb_build_object('id', h.complaint_id, 'date', h.date_received,
             'company', (select t.label from safety.terms t where t.id = h.company_id),
             'product', (select t.label from safety.terms t where t.id = h.product_id),
             'sub_product', (select t.label from safety.terms t where t.id = h.sub_product_id),
             'issue', (select t.label from safety.terms t where t.id = h.issue_id),
             'sub_issue', (select t.label from safety.terms t where t.id = h.sub_issue_id),
             'state', h.state, 'submitted_via', h.submitted_via, 'company_response', h.company_response, 'timely', h.timely,
             'source_url', safety.record_url('cfpb', h.complaint_id::text)) order by h.date_received desc, h.complaint_id desc), '[]'::jsonb)
      into v_total, v_rows
      from (select * from hits order by date_received desc, complaint_id desc limit p_limit offset p_offset) h;
  elsif p_source = 'osha' then
    with hits as (
      select i.* from safety.osha_inspections i
       where (p_from is null or i.open_date >= p_from) and (p_to is null or i.open_date <= p_to)
         and (f->>'estab' is null or i.estab_name = f->>'estab') and (f->>'state' is null or i.site_state = f->>'state')
         and (v_q is null or position(v_q in lower(coalesce(i.estab_name, ''))) > 0))
    select (select count(*) from (select 1 from hits limit c_cap + 1) c),
           coalesce(jsonb_agg(jsonb_build_object('id', h.activity_nr, 'date', h.open_date, 'estab_name', h.estab_name,
             'city', h.site_city, 'state', h.site_state, 'naics', h.naics_code, 'insp_type', h.insp_type, 'scope', h.insp_scope,
             'violations', (select count(*) from safety.osha_violations v where v.activity_nr = h.activity_nr),
             'current_penalty', (select sum(v.current_penalty) from safety.osha_violations v where v.activity_nr = h.activity_nr),
             'source_url', safety.record_url('osha', h.activity_nr::text)) order by h.open_date desc nulls last, h.activity_nr), '[]'::jsonb)
      into v_total, v_rows
      from (select * from hits order by open_date desc nulls last, activity_nr limit p_limit offset p_offset) h;
  else
    with hits as (
      select a.* from safety.osha_accidents a
       where (p_from is null or a.event_date >= p_from) and (p_to is null or a.event_date <= p_to)
         and (v_q is null or position(v_q in lower(coalesce(a.event_desc, '') || ' ' || coalesce(a.abstract, ''))) > 0))
    select (select count(*) from (select 1 from hits limit c_cap + 1) c),
           coalesce(jsonb_agg(jsonb_build_object('id', h.summary_nr, 'date', h.event_date, 'event_desc', h.event_desc,
             'keywords', h.event_keyword, 'fatality', h.fatality, 'injured', jsonb_array_length(h.injuries),
             'inspections', to_jsonb(h.inspections), 'excerpt', left(coalesce(h.abstract, ''), 400),
             'source_url', safety.record_url('osha_accidents', h.summary_nr::text)) order by h.event_date desc nulls last, h.summary_nr), '[]'::jsonb)
      into v_total, v_rows
      from (select * from hits order by event_date desc nulls last, summary_nr limit p_limit offset p_offset) h;
  end if;
  return jsonb_build_object('source', p_source, 'total', least(v_total, c_cap), 'capped', v_total > c_cap, 'rows', v_rows,
    'limit', p_limit, 'offset', p_offset,
    'caveat', safety.caveat(case p_source when 'maude' then 'openfda_maude' when 'nhtsa' then 'nhtsa_complaints'
                              when 'cfpb' then 'cfpb_complaints' else p_source end));
end $$;

-- One record in full, with its official link.
create or replace function public.safety_record_v1(p_source text, p_id text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v jsonb;
begin
  if p_source is null or p_source not in ('maude', 'nhtsa', 'neiss', 'cfpb', 'osha', 'osha_accidents') then
    raise exception 'Invalid source' using errcode = '22023'; end if;
  if p_id is null or p_id !~ '^[A-Za-z0-9][A-Za-z0-9-]{0,40}$' then raise exception 'Invalid id' using errcode = '22023'; end if;
  if p_source = 'maude' then
    select to_jsonb(r) || jsonb_build_object('source_url', safety.record_url('maude', r.report_number, r.mdr_report_key),
             'subjects', (select coalesce(jsonb_agg(jsonb_build_object('subject_id', x.subject_id, 'rule', x.rule)), '[]'::jsonb)
                            from safety.record_subjects x where x.source = 'maude' and x.record_id = r.report_number))
      into v from safety.maude_reports r where r.report_number = p_id;
  elsif p_source = 'nhtsa' and p_id ~ '^[0-9]{1,9}$' then
    select to_jsonb(c) || jsonb_build_object('source_url', safety.record_url('nhtsa', c.odino::text,
             case when c.received >= date '2025-01-01' then 'COMPLAINTS_RECEIVED_2025-2026.zip' else 'COMPLAINTS_RECEIVED_2020-2024.zip' end),
             'subjects', (select coalesce(jsonb_agg(jsonb_build_object('subject_id', x.subject_id, 'rule', x.rule)), '[]'::jsonb)
                            from safety.record_subjects x where x.source = 'nhtsa' and x.record_id = c.odino::text))
      into v from safety.nhtsa_complaints c where c.odino = p_id::integer;
  elsif p_source = 'neiss' and p_id ~ '^[0-9]{1,15}$' then
    select to_jsonb(n) || jsonb_build_object('source_url', safety.record_url('neiss', n.case_number::text, n.file_year::text))
      into v from safety.neiss_cases n where n.case_number = p_id::bigint;
  elsif p_source = 'cfpb' and p_id ~ '^[0-9]{1,15}$' then
    select to_jsonb(c) || jsonb_build_object('source_url', safety.record_url('cfpb', c.complaint_id::text),
             'company', (select t.label from safety.terms t where t.id = c.company_id),
             'product', (select t.label from safety.terms t where t.id = c.product_id),
             'sub_product', (select t.label from safety.terms t where t.id = c.sub_product_id),
             'issue', (select t.label from safety.terms t where t.id = c.issue_id),
             'sub_issue', (select t.label from safety.terms t where t.id = c.sub_issue_id))
      into v from safety.cfpb_complaints c where c.complaint_id = p_id::bigint;
  elsif p_source = 'osha' and p_id ~ '^[0-9]{1,15}$' then
    select to_jsonb(i) || jsonb_build_object('source_url', safety.record_url('osha', i.activity_nr::text),
             'violations', (select coalesce(jsonb_agg(to_jsonb(v0) order by v0.citation_id), '[]'::jsonb)
                              from safety.osha_violations v0 where v0.activity_nr = i.activity_nr),
             'accidents', (select coalesce(jsonb_agg(jsonb_build_object('summary_nr', a.summary_nr, 'event_date', a.event_date,
                              'event_desc', a.event_desc)), '[]'::jsonb) from safety.osha_accidents a where a.inspections @> array[i.activity_nr]))
      into v from safety.osha_inspections i where i.activity_nr = p_id::bigint;
  elsif p_source = 'osha_accidents' and p_id ~ '^[0-9]{1,15}$' then
    select to_jsonb(a) || jsonb_build_object('source_url', safety.record_url('osha_accidents', a.summary_nr::text))
      into v from safety.osha_accidents a where a.summary_nr = p_id::bigint;
  end if;
  return v;
end $$;

-- Company facts per source, by the exact name each source publishes (never merged across sources). Identifiers: the
-- CMS Open Payments manufacturer ids published with that exact name; an insights company entity is named only when
-- its id is exactly 'op-' || that CMS id.
create or replace function public.safety_company_profile_v1(p_name text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_cfpb integer; v_ids text[]; v_entities jsonb := '[]';
begin
  if p_name is null or length(btrim(p_name)) not between 2 and 200 then raise exception 'Invalid name' using errcode = '22023'; end if;
  select t.id into v_cfpb from safety.terms t where t.kind = 'cfpb_company' and t.label = p_name;
  v_ids := array(select distinct o.manufacturer_id from safety.open_payments o where o.manufacturer_name = p_name order by 1);
  if to_regclass('insights.entities') is not null and cardinality(v_ids) > 0 then
    execute 'select coalesce(jsonb_agg(jsonb_build_object(''type'', e.entity_type, ''id'', e.entity_id, ''label'', e.label, ''href'', e.href)), ''[]''::jsonb)
               from insights.entities e where e.entity_type = ''company'' and e.entity_id = any ($1)'
      into v_entities using array(select 'op-' || i from unnest(v_ids) i);
  end if;
  return jsonb_build_object('name', p_name, 'merged_across_sources', false,
    'identifiers', jsonb_build_object('cms_open_payments_ids', to_jsonb(v_ids), 'insights_entities', v_entities),
    'cfpb', case when v_cfpb is null then null else jsonb_build_object('source_id', 'cfpb_complaints',
      'by_year', (select coalesce(jsonb_object_agg(y, n order by y), '{}'::jsonb) from
                   (select extract(year from m.month)::integer::text y, sum(m.complaints) n from safety.cfpb_monthly m where m.company_id = v_cfpb group by 1) a),
      'top_products', (select coalesce(jsonb_agg(jsonb_build_object('product', t.label, 'complaints', a.n) order by a.n desc), '[]'::jsonb) from
                   (select m.product_id, sum(m.complaints) n from safety.cfpb_monthly m where m.company_id = v_cfpb group by 1 order by 2 desc limit 10) a
                   join safety.terms t on t.id = a.product_id),
      'top_issues', (select coalesce(jsonb_agg(jsonb_build_object('issue', t.label, 'complaints', a.n) order by a.n desc), '[]'::jsonb) from
                   (select m.issue_id, sum(m.complaints) n from safety.cfpb_monthly m where m.company_id = v_cfpb group by 1 order by 2 desc limit 10) a
                   join safety.terms t on t.id = a.issue_id),
      'caveat', safety.caveat('cfpb_complaints')) end,
    'osha', (select case when count(*) = 0 then null else jsonb_build_object('source_id', 'dol_osha', 'inspections', count(*),
               'first_open', min(i.open_date), 'last_open', max(i.open_date),
               'violations', (select count(*) from safety.osha_violations v join safety.osha_inspections i2 on i2.activity_nr = v.activity_nr where i2.estab_name = p_name),
               'current_penalty', (select sum(v.current_penalty) from safety.osha_violations v join safety.osha_inspections i2 on i2.activity_nr = v.activity_nr where i2.estab_name = p_name)) end
               from safety.osha_inspections i where i.estab_name = p_name),
    'open_payments', (select case when count(*) = 0 then null else jsonb_build_object('source_id', 'cms_open_payments',
               'by_year', (select coalesce(jsonb_object_agg(y, jsonb_build_object('records', r, 'amount_usd', a) order by y), '{}'::jsonb) from
                   (select o.program_year::text y, sum(o.records) r, sum(o.amount_usd) a from safety.open_payments o where o.manufacturer_name = p_name group by 1) b),
               'top_products', (select coalesce(jsonb_agg(jsonb_build_object('product', b.product, 'amount_usd', b.a) order by b.a desc), '[]'::jsonb) from
                   (select o.product, sum(o.amount_usd) a from safety.open_payments o where o.manufacturer_name = p_name group by 1 order by 2 desc limit 10) b)) end
               from safety.open_payments o where o.manufacturer_name = p_name),
    'nhtsa', (select case when count(*) = 0 then null else jsonb_build_object('source_id', 'nhtsa_complaints', 'complaints', count(*),
               'crash', count(*) filter (where c.crash), 'fire', count(*) filter (where c.fire),
               'injured', sum(c.injured), 'deaths', sum(c.deaths), 'first', min(c.received), 'last', max(c.received),
               'caveat', safety.caveat('nhtsa_complaints')) end
               from safety.nhtsa_complaints c where c.manufacturer = p_name),
    'maude', (select case when count(*) = 0 then null else jsonb_build_object('source_id', 'openfda_maude',
               'reports_in_stored_records', count(*), 'scope', 'record-level reports stored for MDL device groups only',
               'caveat', safety.caveat('openfda_maude')) end
               from safety.maude_reports r where r.manufacturers @> array[p_name]));
end $$;

