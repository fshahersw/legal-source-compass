-- safety/1 — record-level and fine-grained product-safety data (wave 1025, stream SAFETY), joined to products, MDLs and
-- companies, with the read RPCs the product pages, the product signal timeline (public.product_signals_v1) and the
-- insights family `safety2` (insights-safety2-v1.sql) use.
--
-- What lives here (schema `safety`; builders and loaders: scripts/safety_v2/*, RUNBOOK in docs/safety-signals-2026-10-25.md):
--   subjects / mdl_subjects   products (FAERS generic names, MAUDE product codes), MDL product groups and the national
--                             totals, each with the exact openFDA search it counts; MDL ↔ subject links ONLY where the
--                             official JPML title names the product (or class / manufacturer + device), with the title,
--                             the matched tokens and the basis stored on the link.
--   series / series_meta      monthly counts per subject (FAERS reports, serious, deaths, outcome criteria; MAUDE reports by
--                             event type; FDA enforcement reports and device recalls; NHTSA complaints) with the query URL.
--   terms / breakdowns        term counts per subject and period (MedDRA preferred terms by quarter with serious counts,
--                             device problems, brand names); breakdown_meta records the request limit and whether it was hit.
--   maude_reports             record-level MAUDE reports for the devices MDL titles name (record_subjects says which group).
--   nhtsa_complaints          record-level NHTSA ODI complaints received 2020+ (no VIN, city, dealer contact or operator name).
--   neiss_cases               record-level NEISS sample cases (HELD: load only after the lead confirms the owner's
--                             2026-10-23 instruction covers NEISS case records; cpsc_injury_data stays removed, never restored).
--   cfpb_monthly / cfpb_complaints   CFPB complaints: company × product × issue × state × month counts (all years) and the
--                             record-level complaints of the last 24 months (the builder's scope flag says which products).
--   osha_inspections / osha_violations / osha_accidents   DOL OSHA enforcement data catalog (inspections, citations,
--                             accident investigations with their abstracts). OSHA Severe Injury Reports are NOT here:
--                             the record-level file answers 403 (osha.gov bot wall) and is not fetched.
--   open_payments             CMS Open Payments general payments: program year × manufacturer (CMS id) × product named
--                             first on the record × recipient state (records, amount).
--   loads                     one ledger row per loader call (target, rows, inserted/updated/unchanged, part, sha256).
--
-- Accuracy rules carried by the data: every count is the number the source returned for the stored query; a value the
-- source does not give is absent (read RPCs say "not recorded"), never 0 — except series months inside a subject's
-- coverage window, where openFDA's date counts omit days without reports, so an omitted month inside the window IS 0 and
-- is returned as 0 by product_signals_v1 (coverage window in series_meta). Adverse-event and device reports are
-- voluntary, unverified reports; they do not establish that a product caused an event (caveat returned with every series).
-- Companies are never merged across sources: a company profile is per source, by the exact published name or id.
--
-- Every public function: SECURITY DEFINER, search_path = '', revoked from public/anon/authenticated, granted to
-- service_role. Idempotent (create if not exists / create or replace / on conflict). Writes only through
-- public.safety_load_v1 (builders, the lead) and public.safety_ingest_apply_v1 (scheduled edge functions, ingest/1 runs).
-- Offline test: node --test scripts/safety_v2/safety-signals-contract.test.mjs (pglite, synthetic rows).

