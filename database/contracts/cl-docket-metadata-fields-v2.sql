-- cl-docket-metadata-fields/2026-10-27.v2
-- Release of the CourtListener docket header fields that the docket-metadata projection
-- (courtlistener-docket-metadata-view/1, docs/docket-metadata-projection-2026-10-02.md) held back for
-- caution: caption (case_name, case_name_full, case_name_short), cause, nature_of_suit, jury_demand,
-- jurisdiction_type, the assigned and referred judge (name and CourtListener person id), panel,
-- appeal-from court and CourtListener's mdl_status.
--
-- Basis: owner decision 2026-10-27 ("dont withhold any data. If its accurate and valuable, USE IT")
-- and owner rule 2026-10-22 (3) (judges and parties exactly as the publisher shows them).
-- Values are copied verbatim (trimmed; empty string -> null, shown as "Not recorded") from the
-- staged CourtListener docket entity whose native id equals the published row's native id. Nothing is
-- inferred, merged or normalised ("Federal question" and "Federal Question" stay as recorded).
--
-- STILL HELD (explicit source evidence): every docket that CourtListener itself marks blocked
-- (blocked = true/t) or date_blocked. That is 31 of the 187,900 staged dockets; 15 of them are already
-- published as docket-number-only rows (ordinals 186924-186940 additive set). Those 15 rows get NO
-- caption, cause or judge fields from this contract. Quarantined staged entities are skipped too.
-- Not touched: the 956 candidate-only dockets (outside the dataset's explicit-evidence scope),
-- the FJC MDL label ("FJC MDL number", never verified membership), ids, ordinals, links, categories.
--
-- WRITES (lead only, never the app): one private backup table + one private dataset-metadata backup,
-- then bounded in-place updates of public.corpus_records (dataset cl_docket_metadata) and one update
-- of public.corpus_datasets.metadata. search_vector is regenerated by corpus_records_search_vector_trg
-- (title/text change). The semantic refresh triggers do not fire for this dataset.
-- Rollback: database/contracts/cl-docket-metadata-fields-v2.rollback.sql
--
-- ORDER: step 1 once; step 2 once per window (8 windows of 25,000 ordinals: 0-25000, 25000-50000, ...,
-- 175000-200000; edit ONLY the two bounds in `win`); step 3 once after every window; step 4 (verify).
-- Every step is idempotent: re-running a window skips rows that already carry the released fields.

-- ===================================================================== step 1: backups
begin;
create table if not exists corpus_ingest.cl_docket_metadata_fields_backup_20261027 (
  id text primary key,
  ordinal bigint not null,
  title text,
  item jsonb,
  detail jsonb,
  text text,
  filters jsonb,
  fields_md5 text not null,
  backed_up_at timestamptz not null default now()
);
create table if not exists corpus_ingest.cl_docket_metadata_fields_dataset_backup_20261027 (
  dataset text primary key,
  metadata jsonb not null,
  ready boolean,
  backed_up_at timestamptz not null default now()
);
revoke all on corpus_ingest.cl_docket_metadata_fields_backup_20261027 from public, anon, authenticated;
revoke all on corpus_ingest.cl_docket_metadata_fields_dataset_backup_20261027 from public, anon, authenticated;

insert into corpus_ingest.cl_docket_metadata_fields_backup_20261027(id, ordinal, title, item, detail, text, filters, fields_md5)
select r.id, r.ordinal, r.title, r.item, r.detail, r.text, r.filters,
       md5(jsonb_build_array(r.title, r.item, r.detail, r.text, r.filters)::text)
from public.corpus_records r
where r.dataset = 'cl_docket_metadata'
on conflict (id) do nothing;

insert into corpus_ingest.cl_docket_metadata_fields_dataset_backup_20261027(dataset, metadata, ready)
select d.id, d.metadata, d.ready from public.corpus_datasets d where d.id = 'cl_docket_metadata'
on conflict (dataset) do nothing;

do $$ begin
  if (select count(*) from corpus_ingest.cl_docket_metadata_fields_backup_20261027)
     <> (select count(*) from public.corpus_records where dataset = 'cl_docket_metadata') then
    raise exception 'backup row count differs from the published dataset; nothing committed';
  end if;
  if (select count(*) from corpus_ingest.cl_docket_metadata_fields_dataset_backup_20261027) <> 1 then
    raise exception 'dataset metadata backup missing; nothing committed';
  end if;
end $$;
commit;

-- ===================================================================== step 2: release (run per window)
with win as (
  select 0::bigint as lower_ordinal_exclusive, 25000::bigint as upper_ordinal_inclusive
), src as (
  select r.id, r.ordinal, r.title, r.item, r.detail, r.text, r.filters,
         e.native_id, e.data as d, e.schema_version as e_schema, e.payload_sha256 as e_sha,
         e.provenance as e_prov, e.source_as_of as e_as_of, e.retrieved_at as e_retrieved
  from public.corpus_records r
  cross join win w
  join corpus_ingest.cl_docket_metadata_fields_backup_20261027 b on b.id = r.id
  join corpus_ingest.entities e
    on e.source_system = 'courtlistener' and e.entity_type = 'dockets' and r.id = 'cl:dockets:' || e.native_id
  where r.dataset = 'cl_docket_metadata'
    and w.upper_ordinal_inclusive - w.lower_ordinal_exclusive between 1 and 25000
    and r.ordinal > w.lower_ordinal_exclusive and r.ordinal <= w.upper_ordinal_inclusive
    and r.item -> 'cells' ->> 'native_id' = e.native_id
    and e.review_status <> 'quarantined'
    -- explicit CourtListener privacy block: stays held
    and lower(coalesce(e.data ->> 'blocked', 'false')) in ('false', 'f', '0')
    and nullif(e.data ->> 'date_blocked', '') is null
    and nullif(btrim(e.data ->> 'case_name'), '') is not null
    -- only rows unchanged since the backup, and not yet released
    and md5(jsonb_build_array(r.title, r.item, r.detail, r.text, r.filters)::text) = b.fields_md5
    and not (r.item -> 'cells' ? 'case_name')
), fields as (
  select s.*,
    jsonb_build_object(
      'case_name',        nullif(btrim(d ->> 'case_name'), ''),
      'case_name_full',   nullif(btrim(d ->> 'case_name_full'), ''),
      'case_name_short',  nullif(btrim(d ->> 'case_name_short'), ''),
      'cause',            nullif(btrim(d ->> 'cause'), ''),
      'nature_of_suit',   nullif(btrim(d ->> 'nature_of_suit'), ''),
      'jury_demand',      nullif(btrim(d ->> 'jury_demand'), ''),
      'jurisdiction_type',nullif(btrim(d ->> 'jurisdiction_type'), ''),
      'assigned_to_str',  nullif(btrim(d ->> 'assigned_to_str'), ''),
      'assigned_to_id',   coalesce(nullif(d ->> 'assigned_to_id', ''),
                                   substring(d ->> 'assigned_to' from '/people/([0-9]+)/$')),
      'referred_to_str',  nullif(btrim(d ->> 'referred_to_str'), ''),
      'referred_to_id',   coalesce(nullif(d ->> 'referred_to_id', ''),
                                   substring(d ->> 'referred_to' from '/people/([0-9]+)/$')),
      'panel_str',        nullif(btrim(d ->> 'panel_str'), ''),
      'appeal_from_str',  nullif(btrim(d ->> 'appeal_from_str'), ''),
      'mdl_status',       nullif(btrim(d ->> 'mdl_status'), '')
    ) as nf,
    coalesce(nullif(btrim(s.item -> 'cells' ->> 'docket_number'), ''), 'CourtListener docket ' || s.native_id) as dn,
    nullif(btrim(s.item -> 'cells' ->> 'court_id'), '') as ci
  from src s
), built as (
  select f.*,
    btrim(f.nf ->> 'case_name') || ', No. ' || f.dn || coalesce(' (' || f.ci || ')', '') as new_title,
    jsonb_build_object(
      'schema_version', f.e_schema, 'payload_sha256', f.e_sha,
      'source_url', f.e_prov ->> 'source_url', 'source_sha256', f.e_prov ->> 'source_sha256',
      'source_as_of', f.e_as_of::text, 'retrieved_at', f.e_retrieved::text,
      'fields', jsonb_build_array('case_name','case_name_full','case_name_short','cause','nature_of_suit',
        'jury_demand','jurisdiction_type','assigned_to_str','assigned_to_id','referred_to_str','referred_to_id',
        'panel_str','appeal_from_str','mdl_status'),
      'released_by', 'cl-docket-metadata-fields/2026-10-27.v2 (owner decision 2026-10-27)'
    ) as header_source,
    (select coalesce(jsonb_agg(x.fact), '[]'::jsonb) from (
       select jsonb_build_array(lbl, f.nf ->> k) as fact
       from (values (1,'case_name','Case name'),(2,'case_name_full','Full case name'),
                    (3,'cause','Cause (as recorded)'),(4,'nature_of_suit','Nature of suit (as recorded)'),
                    (5,'jury_demand','Jury demand'),(6,'jurisdiction_type','Jurisdiction type (as recorded)'),
                    (7,'assigned_to_str','Assigned judge (as recorded)'),(8,'referred_to_str','Referred judge (as recorded)'),
                    (9,'panel_str','Panel (as recorded)'),(10,'appeal_from_str','Appeal from (as recorded)'),
                    (11,'mdl_status','MDL status (as recorded by CourtListener)')) v(o, k, lbl)
       where f.nf ->> k is not null
       order by v.o) x) as new_facts
  from fields f
), expected as (
  select b.id,
    b.new_title as title,
    jsonb_set(jsonb_set(b.item, '{title}', to_jsonb(b.new_title)), '{cells}',
              (b.item -> 'cells') || b.nf || jsonb_build_object('name', b.new_title)) as item,
    jsonb_set(jsonb_set(jsonb_set(
      case when b.filters ->> 'selection_basis' = 'header_and_upload_agree'
           then jsonb_set(b.detail, '{provenance}',
                  ((b.detail -> 'provenance') - 'caption_agreed_and_withheld')
                  || jsonb_build_object('withheld_fields',
                       coalesce((select jsonb_agg(w.v) from jsonb_array_elements(b.detail -> 'provenance' -> 'withheld_fields') w(v)
                                 where w.v #>> '{}' <> 'case_name'), '[]'::jsonb)))
           else b.detail end,
      '{title}', to_jsonb(b.new_title)),
      '{provenance,header_source}', b.header_source),
      '{qualification}', to_jsonb(case when b.filters ->> 'selection_basis' = 'header_and_upload_agree'
        then 'Docket number, court and dates are published where the owner upload and the stored CourtListener header agree. Caption, cause, nature of suit, jury demand, jurisdiction type and judge fields are shown exactly as the stored CourtListener header records them. This row is not an FJC member association, a master designation, or a transfer ruling.'
        else 'Docket header as CourtListener publishes it, selected by an exact saved native docket ID or a native FJC foreign key with an explicit positive MDL number. Caption, cause, nature of suit, jury demand, jurisdiction type and judge fields are shown exactly as CourtListener records them; a judge name here is not a link to a judge profile. FJC MDL numbers are dated source associations, not a current member-case census, master designation, transfer ruling, claim determination or legal outcome. Unconfirmed candidate and CourtListener-blocked dockets are excluded. Document contents are not part of this header; no PDFs were downloaded.' end))
    || jsonb_build_object('facts',
         (select coalesce(jsonb_agg(z.v order by z.o), '[]'::jsonb) from (
            select fa.v, fa.o * 100 as o from jsonb_array_elements(b.detail -> 'facts') with ordinality fa(v, o)
            union all
            select nf.v, coalesce((select min(fa2.o) from jsonb_array_elements(b.detail -> 'facts') with ordinality fa2(v, o)
                          where fa2.v ->> 0 = 'Court ID'), 1000) * 100 + nf.o
            from jsonb_array_elements(b.new_facts) with ordinality nf(v, o)) z)) as detail,
    jsonb_pretty(((b.item -> 'cells') || b.nf) - 'name') as text,
    b.filters || jsonb_build_object(
      'nature_of_suit', coalesce(b.nf ->> 'nature_of_suit', ''),
      'jurisdiction_type', coalesce(b.nf ->> 'jurisdiction_type', ''),
      'assigned_to_id', coalesce(b.nf ->> 'assigned_to_id', '')) as filters
  from built b
), written as (
  update public.corpus_records r
     set title = x.title, item = x.item, detail = x.detail, text = x.text, filters = x.filters
    from expected x
   where r.dataset = 'cl_docket_metadata' and r.id = x.id
  returning r.id, r.ordinal
)
select jsonb_build_object('contract', 'cl-docket-metadata-fields/2026-10-27.v2',
  'lower_ordinal_exclusive', (select lower_ordinal_exclusive from win),
  'upper_ordinal_inclusive', (select upper_ordinal_inclusive from win),
  'expected', (select count(*) from expected), 'written', (select count(*) from written),
  'min_ordinal', (select min(ordinal) from written), 'max_ordinal', (select max(ordinal) from written),
  'checked_at', now()) as receipt;

-- ===================================================================== step 3: dataset metadata (once, after all windows)
begin;
update public.corpus_datasets d
   set metadata = jsonb_set(jsonb_set(jsonb_set(d.metadata,
       '{qualification}', to_jsonb('Dated CourtListener docket headers selected by exact saved native IDs or explicit native FJC MDL numbers. Captions, cause, nature of suit, jury demand, jurisdiction type and assigned/referred judges are shown exactly as CourtListener records them. FJC associations are not a verified current MDL member-case census. 956 unconfirmed source candidates are outside this dataset. CourtListener-blocked or date-blocked dockets and quarantined courts carry no caption or judge fields. No document contents or PDFs.'::text)),
       '{listing,columns}', jsonb_build_array(
         jsonb_build_object('key','name','label','Case'),
         jsonb_build_object('key','docket_number','label','Docket number'),
         jsonb_build_object('key','court_id','label','Native court ID'),
         jsonb_build_object('key','nature_of_suit','label','Nature of suit'),
         jsonb_build_object('key','assigned_to_str','label','Assigned judge'),
         jsonb_build_object('key','mdl_number','label','FJC MDL number'),
         jsonb_build_object('key','date_filed','label','Filed (source)'),
         jsonb_build_object('key','date_terminated','label','Terminated (source)'))),
       '{listing,filters}',
         coalesce((select jsonb_agg(f.v) from jsonb_array_elements(d.metadata -> 'listing' -> 'filters') f(v)
                   where f.v ->> 'name' <> 'nature_of_suit'), '[]'::jsonb)
         || jsonb_build_array(jsonb_build_object('name','nature_of_suit','type','select','label','Nature of suit (as recorded)',
              'options', (select jsonb_agg(jsonb_build_object('value', n.v, 'label', n.v, 'count', n.c) order by n.c desc, n.v)
                          from (select r.filters ->> 'nature_of_suit' v, count(*) c from public.corpus_records r
                                where r.dataset = 'cl_docket_metadata' and coalesce(r.filters ->> 'nature_of_suit', '') <> ''
                                group by 1) n))))
       || jsonb_build_object('fields_release_2026_10_27', jsonb_build_object(
            'contract', 'cl-docket-metadata-fields/2026-10-27.v2',
            'rule', 'owner decision 2026-10-27; CourtListener blocked/date_blocked dockets stay held',
            'rows_with_caption', (select count(*) from public.corpus_records r where r.dataset = 'cl_docket_metadata' and r.item -> 'cells' ? 'case_name'),
            'rows_held_source_blocked', (select count(*) from public.corpus_records r where r.dataset = 'cl_docket_metadata' and not (r.item -> 'cells' ? 'case_name')),
            'released_at', now()))
 where d.id = 'cl_docket_metadata'
   and exists (select 1 from corpus_ingest.cl_docket_metadata_fields_dataset_backup_20261027 b where b.dataset = d.id);
commit;

-- ===================================================================== step 4: verify (read-only)
set local statement_timeout = '120s';
select
  count(*) as total,                                                             -- expect 186,940 (unchanged)
  count(*) filter (where title like 'Docket %') as docket_placeholder_titles,     -- expect 15 (CourtListener-blocked; was 186,940)
  count(*) filter (where item -> 'cells' ? 'case_name') as with_caption,          -- expect 186,925
  count(*) filter (where item -> 'cells' ->> 'nature_of_suit' is not null) as with_nos,         -- expect 186,859
  count(*) filter (where item -> 'cells' ->> 'assigned_to_str' is not null) as with_assigned,    -- expect 172,764
  count(distinct ordinal) as distinct_ordinals, min(ordinal), max(ordinal)       -- expect 186,940 / 1 / 186,940
from public.corpus_records where dataset = 'cl_docket_metadata';

-- No CourtListener-blocked docket carries a caption (expect 0):
select count(*) as blocked_with_caption
from public.corpus_records r
join corpus_ingest.entities e on e.source_system = 'courtlistener' and e.entity_type = 'dockets' and r.id = 'cl:dockets:' || e.native_id
where r.dataset = 'cl_docket_metadata' and r.item -> 'cells' ? 'case_name'
  and (lower(coalesce(e.data ->> 'blocked', 'false')) not in ('false', 'f', '0') or nullif(e.data ->> 'date_blocked', '') is not null);

-- Every released caption equals the staged source exactly (expect 0):
select count(*) as caption_mismatch
from public.corpus_records r
join corpus_ingest.entities e on e.source_system = 'courtlistener' and e.entity_type = 'dockets' and r.id = 'cl:dockets:' || e.native_id
where r.dataset = 'cl_docket_metadata' and r.item -> 'cells' ? 'case_name'
  and (r.item -> 'cells' ->> 'case_name' is distinct from nullif(btrim(e.data ->> 'case_name'), '')
    or r.item -> 'cells' ->> 'assigned_to_str' is distinct from nullif(btrim(e.data ->> 'assigned_to_str'), '')
    or r.item -> 'cells' ->> 'nature_of_suit' is distinct from nullif(btrim(e.data ->> 'nature_of_suit'), ''));

-- The FJC label and MDL filters are unchanged against the backup (expect 0):
select count(*) as mdl_changed
from public.corpus_records r join corpus_ingest.cl_docket_metadata_fields_backup_20261027 b on b.id = r.id
where r.dataset = 'cl_docket_metadata'
  and (r.filters ->> 'mdl_number' is distinct from b.filters ->> 'mdl_number'
    or r.item -> 'cells' ->> 'mdl_number_raw' is distinct from b.item -> 'cells' ->> 'mdl_number_raw'
    or r.ordinal <> b.ordinal or r.item -> 'links' <> b.item -> 'links');

-- Search finds a caption (expect >= 1):
select count(*) from public.corpus_records
where dataset = 'cl_docket_metadata' and search_vector @@ websearch_to_tsquery('english', 'Janssen Research');
