-- caselaw-read/1 — case-law reading store index, case metadata, Supreme Court full-text index (stage 2).
-- Source: CourtListener bulk data 2026-09-30 (opinions, clusters, dockets, citations, citation map, parentheticals,
-- courts, people). Opinion text and per-case citator lists live in private object storage (bucket corpus-originals,
-- prefixes caselaw/read/2026-09-30/ and caselaw/citator/2026-09-30/); this schema holds only small metadata rows,
-- byte pointers into those objects (one HTTP Range request per page) and a tsvector per Supreme Court opinion
-- (the text itself is not stored here).
-- Blocked clusters/dockets (CourtListener's flag) are never loaded.
-- Every function: SECURITY DEFINER, search_path = '', revoked from public/anon/authenticated, granted to service_role.
-- Idempotent (create if not exists / create or replace). A reload upserts by cluster_id / opinion_id (and part); an
-- identical row is left alone; nothing is deleted.
-- Applied 2026-10-22/23 (worker stage 2) in parts: tables, helpers, read RPCs, load RPCs + grants, then the
-- authorities_ref column (ALTER TABLE ... ADD COLUMN IF NOT EXISTS on an existing install) with the two RPCs that use it,
-- then migrations caselaw_load_skip_unchanged_v1, caselaw_is_citation_v2 and caselaw_fts_format_2 (parts/fts_format
-- columns, opinion_fts_part, caselaw_fulltext_v1, caselaw_status_v1, caselaw_load_fts_v1).
-- Builders: scripts/enrichment/caselaw/{read_store,citator,case_meta,load_caselaw}.py

begin;

create schema if not exists caselaw;
revoke all on schema caselaw from public, anon, authenticated;

-- ------------------------------------------------------------------------------------------------ tables
create table if not exists caselaw.objects (
  id integer generated by default as identity primary key,
  key text not null unique check (key ~ '^caselaw/(read|citator)/2026-09-30/[a-z0-9_./-]+[.]jsonl[.]gz$'),
  kind text not null check (kind in ('read', 'citator')),
  bytes bigint not null check (bytes > 0),
  sha256 text not null check (sha256 ~ '^[a-f0-9]{64}$'),
  loaded_at timestamptz not null default now()
);

create table if not exists caselaw.courts (
  court_id text primary key check (court_id ~ '^[a-z0-9_-]{1,40}$'),
  tier smallint not null check (tier in (1, 2, 3)),
  full_name text not null,
  short_name text,
  citation_string text,
  cases integer not null default 0
);

create table if not exists caselaw.cases (
  cluster_id bigint primary key,
  tier smallint not null check (tier in (1, 2, 3)),
  court_id text not null,
  date_filed date,
  date_approx boolean not null default false,
  case_name text not null,
  case_name_full text,
  docket_number text,
  precedential_status text,
  citation_count integer,                -- CourtListener cluster.citation_count, as published
  cited_by integer not null default 0,   -- citing opinions in the citation map (unblocked, other clusters)
  cited_by_cases integer not null default 0,
  parentheticals integer not null default 0,
  authorities integer not null default 0,
  citations text[] not null default '{}',
  cite_keys text[] not null default '{}',
  judges text,
  panel text[],
  disposition text,
  scdb jsonb,                            -- SCDB fields exactly as CourtListener provides them
  opinions jsonb not null default '[]',  -- [{"id","type","author","per_curiam","o","s","n"}]: o = objects.id, s/n = byte offset/length
  citator integer[],                     -- cited-by member: {object id, offset, length} or null
  authorities_ref integer[],             -- cited-authorities member: {object id, offset, length} or null
  name_tsv tsvector not null,
  build text not null,
  check (citator is null or cardinality(citator) = 3),
  constraint cases_authorities_ref_len check (authorities_ref is null or cardinality(authorities_ref) = 3)
);
alter table caselaw.cases add column if not exists authorities_ref integer[];
create index if not exists cases_name_tsv on caselaw.cases using gin (name_tsv);
create index if not exists cases_cite_keys on caselaw.cases using gin (cite_keys);
create index if not exists cases_court_date on caselaw.cases (court_id, date_filed);
create index if not exists cases_cited on caselaw.cases (citation_count desc nulls last);

create table if not exists caselaw.opinion_fts (
  opinion_id bigint primary key,
  cluster_id bigint not null,
  type text,
  tsv tsvector not null,
  tsv_mode smallint not null default 0 check (tsv_mode in (0, 1, 2)),  -- 0 full, 1 positions stripped (size limit), 2 truncated
  text_sha256 text not null check (text_sha256 ~ '^[a-f0-9]{64}$'),
  build text not null
);
create index if not exists opinion_fts_tsv on caselaw.opinion_fts using gin (tsv);
create index if not exists opinion_fts_cluster on caselaw.opinion_fts (cluster_id);
-- Index format 2 (2026-10-23): star-page markers ("*710" at the recorded page offsets) are blanked before indexing, so
-- the word glued to a marker is indexed as a word; the text is indexed in parts of 8,000 words (+40 words of overlap)
-- because tsvector positions stop at 16,383, beyond which phrase search fails. opinion_fts holds part 0 of every
-- opinion (parts = how many), opinion_fts_part the further parts of long opinions.
alter table caselaw.opinion_fts add column if not exists parts smallint;
alter table caselaw.opinion_fts add column if not exists fts_format smallint;
create table if not exists caselaw.opinion_fts_part (
  opinion_id bigint not null,
  part smallint not null check (part >= 1),
  cluster_id bigint not null,
  type text,
  tsv tsvector not null,
  tsv_mode smallint not null default 0 check (tsv_mode in (0, 1, 2)),
  text_sha256 text not null check (text_sha256 ~ '^[a-f0-9]{64}$'),  -- of the whole opinion text
  build text not null,
  primary key (opinion_id, part)
);
create index if not exists opinion_fts_part_tsv on caselaw.opinion_fts_part using gin (tsv);
create index if not exists opinion_fts_part_cluster on caselaw.opinion_fts_part (cluster_id);
alter table caselaw.opinion_fts_part enable row level security;

alter table caselaw.objects enable row level security;
alter table caselaw.courts enable row level security;
alter table caselaw.cases enable row level security;
alter table caselaw.opinion_fts enable row level security;
revoke all on all tables in schema caselaw from public, anon, authenticated;

-- ------------------------------------------------------------------------------------------------ helpers
create or replace function caselaw.name_doc(p text) returns text
language sql immutable parallel safe set search_path = '' as $$
  select btrim(regexp_replace(' ' || regexp_replace(lower(coalesce(p, '')), '[^[:alnum:]]+', ' ', 'g') || ' ', '( (v|vs))+ ', ' ', 'g'))
$$;

create or replace function caselaw.cite_key(p text) returns text
language sql immutable parallel safe set search_path = '' as $$
  select regexp_replace(lower(coalesce(p, '')), '[^[:alnum:]]+', '', 'g')
$$;

-- "volume reporter page": reporters such as "Mart. (N.S.)", "Serg. & Rawle", "F. App’x", "A.F.T.R. (P-H)", WL numbers,
-- CCH paragraph numbers ("43,870") and suffixed pages ("2005 MT 251N", "2011 NY Slip Op 98720(U)")
create or replace function caselaw.is_citation(p text) returns boolean
language sql immutable parallel safe set search_path = '' as $$
  select coalesce(p ~ '^\s*[0-9]{1,5}\s+[A-Za-z][A-Za-z0-9.''’&(), -]{0,60}\s+[0-9][0-9,]{0,11}[A-Za-z]{0,2}(\([A-Za-z]{1,3}\))?\s*$', false)
$$;

-- name tokens AND-ed, last token as a prefix; null when nothing searchable remains
create or replace function caselaw.name_query(p text) returns tsquery
language plpgsql immutable parallel safe set search_path = '' as $$
declare toks text[]; q text := ''; i integer;
begin
  toks := array(select t from unnest(regexp_split_to_array(caselaw.name_doc(p), ' ')) t where t <> '' limit 12);
  if cardinality(toks) = 0 then return null; end if;
  for i in 1 .. cardinality(toks) loop
    q := q || case when i > 1 then ' & ' else '' end || quote_literal(toks[i]) || case when i = cardinality(toks) then ':*' else '' end;
  end loop;
  return to_tsquery('simple', q);
end $$;

create or replace function caselaw.text_query(p text) returns tsquery
language plpgsql immutable parallel safe set search_path = '' as $$
declare q tsquery;
begin
  if p is null or btrim(p) = '' or length(p) > 300 then return null; end if;
  q := websearch_to_tsquery('english', p);
  if q::text = '' then return null; end if;
  return q;
end $$;

create or replace function caselaw.object_key(p_id integer) returns text
language sql stable set search_path = '' as $$ select key from caselaw.objects where id = p_id $$;

create or replace function caselaw.row_summary(c caselaw.cases) returns jsonb
language sql stable set search_path = '' as $$
  select jsonb_build_object('cluster_id', c.cluster_id, 'tier', c.tier, 'court_id', c.court_id,
    'court', (select coalesce(k.short_name, k.full_name) from caselaw.courts k where k.court_id = c.court_id),
    'date_filed', c.date_filed, 'case_name', c.case_name, 'citations', to_jsonb(c.citations),
    'precedential_status', c.precedential_status, 'citation_count', c.citation_count, 'cited_by', c.cited_by,
    'docket_number', c.docket_number, 'has_text', jsonb_path_exists(c.opinions, '$[*].o'))
$$;

