      'schema_total', (select sum(pg_total_relation_size(c.oid)) from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid = c.relnamespace
                       where n.nspname = 'caselaw' and c.relkind = 'r')))
$$;

-- ------------------------------------------------------------------------------------------------ load RPCs (builder only)
create or replace function public.caselaw_load_objects_v1(p_rows jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb; v_id integer; v_out jsonb := '{}'::jsonb; v_sha text;
begin
  if jsonb_typeof(p_rows) is distinct from 'array' or jsonb_array_length(p_rows) not between 1 and 5000 then
    raise exception 'Invalid object batch' using errcode = '22023'; end if;
  for r in select * from jsonb_array_elements(p_rows) loop
    select id, sha256 into v_id, v_sha from caselaw.objects where key = r ->> 'key';
    if v_id is null then
      insert into caselaw.objects(key, kind, bytes, sha256) values (r ->> 'key', r ->> 'kind', (r ->> 'bytes')::bigint, r ->> 'sha256')
      returning id into v_id;
    elsif v_sha <> r ->> 'sha256' then
      raise exception 'Object % already registered with another sha256', r ->> 'key' using errcode = '23505';
    end if;
    v_out := v_out || jsonb_build_object(r ->> 'key', v_id);
  end loop;
  return v_out;
end $$;

create or replace function public.caselaw_load_courts_v1(p_rows jsonb) returns integer
language sql security definer set search_path = '' as $$
  with ins as (
    insert into caselaw.courts(court_id, tier, full_name, short_name, citation_string, cases)
    select r ->> 'court_id', (r ->> 'tier')::smallint, r ->> 'full_name', r ->> 'short_name', r ->> 'citation_string', (r ->> 'cases')::integer
    from jsonb_array_elements(p_rows) r
    on conflict (court_id) do update set tier = excluded.tier, full_name = excluded.full_name, short_name = excluded.short_name,
      citation_string = excluded.citation_string, cases = excluded.cases
    returning 1)
  select count(*)::integer from ins
$$;

create or replace function public.caselaw_load_cases_v1(p_build text, p_rows jsonb) returns integer
language plpgsql security definer set search_path = '' as $$
declare n integer;
begin
  if p_build !~ '^[a-z0-9_.-]{1,40}$' then raise exception 'Invalid build' using errcode = '22023'; end if;
  if jsonb_typeof(p_rows) is distinct from 'array' or jsonb_array_length(p_rows) not between 1 and 5000 then
    raise exception 'Invalid case batch' using errcode = '22023'; end if;
  insert into caselaw.cases(cluster_id, tier, court_id, date_filed, date_approx, case_name, case_name_full, docket_number,
    precedential_status, citation_count, cited_by, cited_by_cases, parentheticals, authorities, citations, cite_keys, judges, panel,
    disposition, scdb, opinions, citator, authorities_ref, name_tsv, build)
  select (r ->> 'cluster_id')::bigint, (r ->> 'tier')::smallint, r ->> 'court_id', (r ->> 'date_filed')::date,
    coalesce((r ->> 'date_approx')::boolean, false), r ->> 'case_name', r ->> 'case_name_full', r ->> 'docket_number',
    r ->> 'precedential_status', (r ->> 'citation_count')::integer, coalesce((r ->> 'cited_by')::integer, 0),
    coalesce((r ->> 'cited_by_cases')::integer, 0), coalesce((r ->> 'parentheticals')::integer, 0), coalesce((r ->> 'authorities')::integer, 0),
    coalesce(array(select jsonb_array_elements_text(r -> 'citations')), '{}'),
    coalesce(array(select distinct caselaw.cite_key(x) from jsonb_array_elements_text(r -> 'citations') x), '{}'),
    r ->> 'judges', case when jsonb_typeof(r -> 'panel') = 'array' then array(select jsonb_array_elements_text(r -> 'panel')) end,
    r ->> 'disposition', case when jsonb_typeof(r -> 'scdb') = 'object' then r -> 'scdb' end,
    coalesce(r -> 'opinions', '[]'::jsonb),
    case when jsonb_typeof(r -> 'citator') = 'array' then array(select (jsonb_array_elements_text(r -> 'citator'))::integer) end,
