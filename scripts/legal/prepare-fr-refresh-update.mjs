// Writes database/contracts/legal-atlas-v3-fr-refresh.sql: the production update for the
// Federal Register refresh. record_errors is copied verbatim from the generated contract
// (scripts/legal/generate-db.ts), so the database and the application validator agree.
//   node scripts/legal/prepare-fr-refresh-update.mjs [--check]
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';

export const FR_REFRESH_SQL = 'database/contracts/legal-atlas-v3-fr-refresh.sql';

export function frRefreshSql(generated) {
  const start = generated.indexOf('create function legal_atlas.record_errors(');
  const end = generated.indexOf('\n$$;', start) + 4;
  if (start < 0 || end < start) throw new Error('Missing function: record_errors');
  const recordErrors = generated.slice(start, end).replace('create function', 'create or replace function');
  if (!/create type legal_atlas\.fr_document_type as enum \([^)]*'CORRECTION'/.test(generated)) throw new Error('Generated contract lacks the CORRECTION document type');
  return `-- Legal atlas Federal Register refresh. Generated by scripts/legal/prepare-fr-refresh-update.mjs; do not edit by hand.
-- Additive and loosening only: no row is changed, removed, approved or released.
-- Apply statement 1 by itself first (a new enum value cannot be used in the transaction that adds it),
-- then the rest in one transaction.

-- 1. The publisher's pre-2009 "Correction" document type.
alter type legal_atlas.fr_document_type add value if not exists 'CORRECTION';

-- 2. Record validation, identical to database/contracts/legal-atlas-v3.generated.sql: accepts the
--    publisher's republication numbers (R1-2026-05038) beside corrections (C1-...). Only loosens.
${recordErrors}
revoke all on function legal_atlas.record_errors(jsonb) from public,anon,authenticated;
grant execute on function legal_atlas.record_errors(jsonb) to service_role;

-- 3. Refresh window, read-only, for scripts/legal/refresh-federal-register.mjs --live-held:
--    the newest publication date held and, from p_from on, the publications already held
--    (exact publisher URL), so a refresh never stages a second version of a held document.
create or replace function public.corpus_legal_fr_window_v3(p_from date default null)
returns jsonb language sql stable security invoker set search_path='' as $$
  with recent as (
    select r.id, r.payload->>'source_url' as source_url, r.payload->>'date' as published
    from legal_atlas.records r
    where r.type in ('fr_document','source_doc') and r.payload->>'source_name'='Federal Register'
      and ((r.id >= (extract(year from least(coalesce(p_from,current_date),current_date))::integer-1)::text||'-'
            and r.id < (extract(year from current_date)::integer+1)::text||'-')
        or (r.id >= 'C' and r.id < 'D') or (r.id >= 'R' and r.id < 'S'))
  )
  select jsonb_build_object(
    'latest_published',(select max(published) from recent),
    'from',p_from,
    'held',case when p_from is null then '[]'::jsonb else coalesce((
      select jsonb_agg(jsonb_build_object('id',h.id,'source_url',h.source_url,'published',h.published) order by h.published,h.id)
      from (select distinct id,source_url,published from recent where published>=p_from::text) h),'[]'::jsonb) end,
    'as_of',now());
$$;
revoke all on function public.corpus_legal_fr_window_v3(date) from public,anon,authenticated;
grant execute on function public.corpus_legal_fr_window_v3(date) to service_role;

-- 4. One current payload per publication. 3,130 documents published 2026-08-21..2026-10-02 hold a
--    second, reduced version (a "dates" field set without RINs, dockets or comments_close_on) staged
--    from the quality reference fetch in run 32a13707-42a1-ee42-17f9-252a5dac9aa8. Readers use this
--    view: per document number and publisher URL it keeps the complete API version. Nothing is deleted.
create or replace view legal_atlas.fr_documents_current with (security_invoker=true) as
  select distinct on (r.id, r.payload->>'source_url')
    r.record_key, r.input_key, r.type, r.id, r.version, r.payload, r.review_status,
    case when r.payload->'attributes'->'native' ? 'regulation_id_numbers' then 'api_full' else 'reference_reduced' end as payload_shape
  from legal_atlas.records r
  where r.type='fr_document'
  order by r.id, r.payload->>'source_url', (r.payload->'attributes'->'native' ? 'regulation_id_numbers') desc,
    r.payload->>'retrieved_at' desc, r.version;
revoke all on legal_atlas.fr_documents_current from public,anon,authenticated;
grant select on legal_atlas.fr_documents_current to service_role;
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const sql = frRefreshSql(fs.readFileSync('database/contracts/legal-atlas-v3.generated.sql', 'utf8'));
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(FR_REFRESH_SQL) || fs.readFileSync(FR_REFRESH_SQL, 'utf8') !== sql) throw new Error(`${FR_REFRESH_SQL} differs from the generated contract; rerun this script`);
  } else fs.writeFileSync(FR_REFRESH_SQL, sql);
  console.log(JSON.stringify({ written: FR_REFRESH_SQL, check: process.argv.includes('--check') }));
}
