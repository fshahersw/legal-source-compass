"""Regenerate src/lib/ingest/sources/enforcementLookups.ts from the DOJ/SEC builders' saved lookups (and, when given,
the DOJ boilerplate key set from doj_boilerplate.py), so scheduled runs link companies and courts exactly as the
builders did. The lookups are the builders' own files; nothing is fetched.

  python3 -I -B scripts/api_law/enforcement/gen_lookups.py [--boilerplate private/build/w1025_api-law/doj/boilerplate.json]
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EA = ROOT / "scripts" / "enrichment" / "enforcement_actions"
TARGET = ROOT / "src" / "lib" / "ingest" / "sources" / "enforcementLookups.ts"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--boilerplate")
    a = ap.parse_args()
    companies_path = EA / "lookup_company_sec_profiles.json"
    courts_path = EA / "lookup_court_spine_ids.json"
    companies = json.loads(companies_path.read_text())
    courts = json.loads(courts_path.read_text())
    boiler = {"keys": [], "min_releases": 25, "releases": None, "pages_sha256": None}
    if a.boilerplate:
        b = json.loads(Path(a.boilerplate).read_text())
        boiler = {"keys": b["keys"], "min_releases": b["min_releases"], "releases": b["releases"], "pages_sha256": b["pages_sha256"]}
    elif TARGET.exists():
        # keep the key set already generated
        text = TARGET.read_text()
        start = text.index("export const DOJ_BOILERPLATE = ") + len("export const DOJ_BOILERPLATE = ")
        boiler = json.loads(text[start:text.index(";\n", start)])
    lines = [
        "/**",
        " * Saved lookups of the DOJ and SEC builders (scripts/enrichment/enforcement_actions/lookup_*.json) and the DOJ",
        " * boilerplate sentence keys of the base build (scripts/api_law/enforcement/doj_boilerplate.py), for the scheduled",
        " * DOJ and SEC refreshes. Generated by scripts/api_law/enforcement/gen_lookups.py; do not edit by hand.",
        " */",
        "/* eslint-disable */",
        "export const COMPANY_LOOKUP = " + json.dumps({"source": companies.get("source"), "retrieved_at": companies.get("retrieved_at"),
                                                       "sha256": digest(companies_path), "rows": companies["rows"]}, ensure_ascii=False) + " as { source: string; retrieved_at: string; sha256: string; rows: [string, string][] };",
        "export const COURT_LOOKUP = " + json.dumps({"source": courts.get("source"), "retrieved_at": courts.get("retrieved_at"),
                                                     "sha256": digest(courts_path), "courts": courts["courts"]}, ensure_ascii=False) + " as { source: string; retrieved_at: string; sha256: string; courts: Record<string, string> };",
        "export const DOJ_BOILERPLATE = " + json.dumps(boiler) + ";",
        "",
    ]
    TARGET.write_text("\n".join(lines))
    print(json.dumps({"companies": len(companies["rows"]), "courts": len(courts["courts"]), "boilerplate_keys": len(boiler["keys"])}))


if __name__ == "__main__":
    main()
