"""Write private/scratch/enrich/ecfr_full/run_env.mjs: runs one allowed command with the environment node loaded via
--env-file (inside a worktree the shell may not source the credentials file). Nothing from the environment is printed.

  node --env-file=private/scratch/env.sh private/scratch/enrich/ecfr_full/run_env.mjs publish --check|--publish <meta.json>...
  node --env-file=private/scratch/env.sh private/scratch/enrich/ecfr_full/run_env.mjs shoot <port> <outdir> <widths> <path>...
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
DEST = os.path.join(ROOT, "private", "scratch", "enrich", "ecfr_full", "run_env.mjs")

SCRIPT = r'''// Generated by scripts/enrichment/ecfr_full/make_runner.py. Runs one allowed command with process.env as loaded by
// node --env-file; prints nothing from the environment.
import { spawnSync } from "node:child_process";

const [what, ...rest] = process.argv.slice(2);
let cmd, args;
if (what === "publish") {
  const [mode, ...files] = rest;
  if (!["--check", "--publish"].includes(mode) || !files.length || files.some((f) => !/^private\/build\/ecfr_full\/[a-z_]+\.meta\.json$/.test(f))) {
    console.error("usage: run_env.mjs publish --check|--publish private/build/ecfr_full/<dataset>.meta.json ...");
    process.exit(2);
  }
  const resume = rest.includes("--resume-from") ? [] : [];
  cmd = "python3";
  args = ["-I", "-B", "scripts/enrichment/ecfr_full/publish_stream.py", mode, ...files, ...resume];
} else if (what === "publish-resume") {
  const [ordinal, file] = rest;
  if (!/^\d+$/.test(ordinal ?? "") || !/^private\/build\/ecfr_full\/[a-z_]+\.meta\.json$/.test(file ?? "")) process.exit(2);
  cmd = "python3";
  args = ["-I", "-B", "scripts/enrichment/ecfr_full/publish_stream.py", "--publish", file, "--resume-from", ordinal];
} else if (what === "shoot") {
  const [port, outdir, widths, ...paths] = rest;
  if (!/^\d{4}$/.test(port ?? "") || !/^private\/scratch\/enrich\/ecfr_full\/shots\/[a-z0-9_-]+$/.test(outdir ?? "")) process.exit(2);
  cmd = "node";
  args = ["private/scratch/with_server.mjs", "private/scratch/shoot.mjs", outdir, widths, ...paths];
  process.env.LSC_PORT = port;
} else if (what === "script") {
  const [port, script, ...sargs] = rest;
  if (!/^\d{4}$/.test(port ?? "") || !/^private\/scratch\/enrich\/ecfr_full\/[a-z0-9_-]+\.mjs$/.test(script ?? "")) process.exit(2);
  cmd = "node";
  args = ["private/scratch/with_server.mjs", script, ...sargs];
  process.env.LSC_PORT = port;
} else {
  console.error("usage: run_env.mjs publish|publish-resume|shoot|script ...");
  process.exit(2);
}
const r = spawnSync(cmd, args, { env: process.env, stdio: "inherit" });
process.exit(r.status ?? 1);
'''

os.makedirs(os.path.dirname(DEST), exist_ok=True)
with open(DEST, "w", encoding="utf-8") as fh:
    fh.write(SCRIPT)
print(DEST)
