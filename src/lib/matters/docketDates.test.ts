import { describe, expect, it } from "vitest";
import {
  docketedNote,
  extractDocketDates,
  summarizeDates,
  upcomingDates,
  type DatedEntry,
} from "./docketDates";

// Docket text from sw_docket_entries_v1 (MDL 3047 entries 3062, 3428 and the 2142 stipulation order).
const CMO35 =
  "CASE MANAGEMENT ORDER NO. 35: (Trial Plan, Prefiling Conference, et al) Jury Selection set for 2/3/2027, at 08:00 AM in Oakland, Courtroom 1, 4th Floor before Judge Yvonne Gonzalez Rogers. Jury Trial set for 2/8/2027, at 08:00 AM in Oakland, Courtroom 1, 4th Floor before Judge Yvonne Gonzalez Rogers. Signed by Judge Yvonne Gonzalez Rogers on 5/21/2026. (eac, COURT STAFF) (Filed on 5/21/2026)";
const CLERK =
  "CLERK'S NOTICE. You are hereby notified that Jury Trial set for 8/20/2026, is vacated and continued to 8/24/2026, at 8:00 AM in Oakland, Courtroom 1, 4th Floor. (This is a text-only entry generated by the court.) (eac, COURT STAFF) (Filed on 8/20/2026)";
const SCHED =
  "Order by Judge Yvonne Gonzalez Rogers Granting 2142 Stipulation to Modify Pretrial Schedule. Close of Expert Discovery due by 9/17/2025. Defendant's Rule 702 Motion due by 9/30/2025. Plaintiff's Oppos";
const CMO3 =
  "CASE MANAGEMENT ORDER NO. 3. Further Case Management Conference set for 3/3/2023 08:30 AM in Oakland, Courtroom 1, 4th Floor. Signed by Judge Yvonne Gonzalez Rogers on 12/15/2022.";

describe("extractDocketDates", () => {
  it("reads each printed date with the event named before it and its time", () => {
    const d = extractDocketDates(CMO35);
    expect(d.map((x) => [x.label, x.phrase, x.date, x.time, x.vacated])).toEqual([
      ["Jury Selection", "set for", "2027-02-03", "08:00 AM", false],
      ["Jury Trial", "set for", "2027-02-08", "08:00 AM", false],
    ]);
    expect(d[0]!.printed).toBe("2/3/2027");
  });

  it("flags vacated only where the text says so and carries the event to the continued date", () => {
    const d = extractDocketDates(CLERK);
    expect(d.map((x) => [x.label, x.phrase, x.date, x.vacated])).toEqual([
      ["Jury Trial", "set for", "2026-08-20", true],
      ["Jury Trial", "continued to", "2026-08-24", false],
    ]);
  });

  it("reads due-by deadlines with their own labels", () => {
    expect(extractDocketDates(SCHED).map((x) => [x.label, x.date])).toEqual([
      ["Close of Expert Discovery", "2025-09-17"],
      ["Defendant's Rule 702 Motion", "2025-09-30"],
    ]);
    expect(extractDocketDates(CMO3)[0]).toMatchObject({
      label: "Further Case Management Conference",
      date: "2023-03-03",
      time: "08:30 AM",
    });
  });

  it("ignores signature and filing dates and impossible dates", () => {
    expect(extractDocketDates("Signed by Judge A on 5/21/2026. (Filed on 5/21/2026)")).toEqual([]);
    expect(extractDocketDates("Hearing set for 2/30/2027.")).toEqual([]);
    expect(extractDocketDates(null)).toEqual([]);
  });

  it("reads 'reset for' and 'is set for' as their own phrases", () => {
    expect(extractDocketDates("Status Conference reset for 11/6/2026 10:00 AM.")[0]).toMatchObject({
      phrase: "reset for",
      label: "Status Conference",
    });
    expect(extractDocketDates("The Motion Hearing is set for 1/13/2027.")[0]).toMatchObject({
      phrase: "is set for",
      label: "Motion Hearing",
    });
  });
});

const row = (date: string, vacated: boolean, id: string): DatedEntry => ({
  date,
  printed: date,
  phrase: "set for",
  label: "Hearing",
  time: null,
  vacated,
  snippet: "",
  entryId: id,
  entryNumber: 1,
  entryDate: "2026-09-01",
  sourceUrl: null,
});

describe("upcoming and summary", () => {
  const rows = [
    row("2026-11-16", false, "a"),
    row("2027-02-08", false, "b"),
    row("2026-12-01", true, "c"),
    row("2026-01-01", false, "d"),
  ];
  it("keeps only non-vacated dates on or after today, soonest first", () => {
    expect(upcomingDates(rows, "2026-10-27").map((r) => r.entryId)).toEqual(["a", "b"]);
  });
  it("summarizes with the collection date", () => {
    expect(summarizeDates(rows, "2026-10-27", "2026-10-03")).toMatchObject({
      total: 4,
      ahead: 2,
      vacated: 1,
      collectedThrough: "2026-10-03",
    });
    expect(summarizeDates(rows, "2026-10-27", null).next?.entryId).toBe("a");
    expect(summarizeDates(rows, "2026-10-27", null).latest?.entryId).toBe("b");
  });
  it("prints the docketing caveat", () => {
    expect(docketedNote("2026-05-21", "2026-10-03")).toBe(
      "as docketed on 2026-05-21; later changes after 2026-10-03 are not collected",
    );
  });
});
