export function titleFigures(title: string | null | undefined): TitleFigure[] {
  if (!title) return [];
  const found: [RegExpExecArray, boolean][] = [...finditer(AMOUNT, title)].map((m) => [m, true]);
  const taken = found.map(([m]) => [m.index, m.index + m[0].length] as const);
  for (const m of finditer(BARE_AMOUNT, title))
    if (!taken.some(([a, b]) => a < m.index + m[0].length && m.index < b)) found.push([m, false]);
  found.sort((x, y) => x[0].index - y[0].index);
  const out: TitleFigure[] = [];
  for (const [m, dollar] of found) {
    const { value, ranged, ambiguous } = reading(m, title);
    const prior = title.slice(0, m.index);
    const rest = title.slice(m.index + m[0].length);
    let cut = 0;
    for (const b of finditer(CLAUSE_BREAK, prior)) cut = b.index + b[0].length;
    const clause = prior.slice(cut);
    const attachedAfter = match(TITLE_AFTER, rest) !== null;
    const attachedBefore = search(TITLE_BEFORE, clause) !== null || search(TITLE_SETTLE_FOR, clause) !== null;
    const resolution =
      (attachedAfter || (attachedBefore && match(TITLE_NOT_RESOLUTION, rest) === null)) &&
      search(TITLE_NOT_RESOLVED, clause) === null;
    if (!dollar && !resolution && match(DOLLARS_AFTER, rest) === null) continue;
    const f: TitleFigure = { as_written: m[0], offset: cpIndex(title, m.index), resolution };
    const v = ranged || ambiguous ? null : value;
    if (v !== null) f.value_usd = v;
    if (ranged) f.range_start = true;
    if (ambiguous) f.ambiguous_as_written = true;
    out.push(f);
  }
  // Python key order: as_written, offset, value_usd, range_start, ambiguous_as_written, resolution
  return out.map((f) => {
    const o: TitleFigure = { as_written: f.as_written, offset: f.offset } as TitleFigure;
    if (f.value_usd !== undefined) o.value_usd = f.value_usd;
    if (f.range_start) o.range_start = true;
    if (f.ambiguous_as_written) o.ambiguous_as_written = true;
    o.resolution = f.resolution;
    return o;
  });
}

const MONTHS = ["january", "february", "march", "april", "may", "june", "july", "august", "september", "october", "november", "december"];
const MONTH_RE =
  "(?:January|February|March|April|May|June|July|August|September|October|November|December|Jan\\.|Feb\\.|Mar\\.|Apr\\.|Aug\\.|Sept?\\.|Oct\\.|Nov\\.|Dec\\.)";
const EARLIER_START = rx(
  "^(?:In|On|Back in|During)\\s+(?:(?:early|late|mid-?)\\s*)?(?:(?P<month>" + MONTH_RE + ")\\s+)?" +
    "(?:\\d{1,2},?\\s+)?(?:of\\s+)?(?P<year>(?:19|20)\\d{2})\\b",
);
const EARLIER_EVENT = rx(
  "\\b(?:settled|resolved|dismissed|paid)\\b" +
    "(?:\\s+\\w+){0,3}?\\s+in\\s+(?:(?P<month>" + MONTH_RE + ")\\s+)?(?:of\\s+)?(?P<year>(?:19|20)\\d{2})\\b",
  "g",
);
const EARLIER_WORDS = rx(
  "^previously," + "|\\bin (?:a|an) (?:separate|earlier|prior) (?:settlement|case|matter|action|resolution|agreement)\\b",
  "i",
);

function monthIndex(m: RegExpExecArray): number {
  const month = (m.groups?.["month"] ?? "").toLowerCase().replace(/\.+$/, "");
  const idx = month ? MONTHS.findIndex((name) => name.startsWith(month.slice(0, 3))) : -1;
  return Number(m.groups!["year"]) * 12 + (idx >= 0 ? idx + 1 : 12);
}

/** extract.about_earlier_matter */
export function aboutEarlierMatter(sentence: string | null | undefined, releaseDate: string | null | undefined, minMonths = 2): boolean {
  if (!sentence) return false;
  if (search(EARLIER_WORDS, sentence)) return true;
  const m = /^((?:19|20)\d{2})-(\d{2})/.exec(releaseDate ?? "");
  if (!m) return false;
  const released = Number(m[1]) * 12 + Number(m[2]);
  const events: (RegExpExecArray | null)[] = [match(EARLIER_START, sentence), ...finditer(EARLIER_EVENT, sentence)];
  return events.some((e) => e !== null && monthIndex(e) <= released - minMonths);
}

export type Headline = {
  as_written: string;
  value_usd: number;
  source: "title" | "first resolution sentence";
  title_figures?: number;
  keyword?: string;
  sentence?: string | null;
  title_figure_not_used?: string;
  earlier_matter_figures_skipped?: number;
  differs_from_largest?: boolean;
};

/** extract.headline_figure */
export function headlineFigure(
  title: string | null | undefined,
  amounts: Amount[],
  releaseDate: string | null | undefined = null,
  earlierMonths = 2,
): Headline | null {
  const stated = titleFigures(title).filter((f) => f.resolution);
  let rejected: string | null = null;
  if (stated.length) {
    const first = stated[0]!;
    if (first.value_usd !== undefined && first.value_usd < RESOLUTION_CAP_USD) {
      const out: Headline = { as_written: first.as_written, value_usd: first.value_usd, source: "title" };
      if (new Set(stated.map((f) => f.value_usd ?? null)).size > 1) out.title_figures = stated.length;
      return out;
    }
    rejected = first.range_start ? "range" : first.ambiguous_as_written ? "ambiguous as written" : "over cap";
  }
  let skipped = 0;
  for (const a of amounts) {
    if (a.keyword && RESOLUTION_KINDS.has(a.keyword) && !a.boilerplate && a.value_usd !== undefined && a.value_usd < RESOLUTION_CAP_USD) {
      if (aboutEarlierMatter(a.sentence, releaseDate, earlierMonths)) {
        skipped++;
        continue;
      }
      const out: Headline = {
        as_written: a.as_written,
        value_usd: a.value_usd,
        source: "first resolution sentence",
        keyword: a.keyword,
        sentence: a.sentence ?? null,
      };
      if (rejected) out.title_figure_not_used = rejected;
      if (skipped) out.earlier_matter_figures_skipped = skipped;
      return out;
    }
  }
  return null;
}

