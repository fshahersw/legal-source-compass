/**
 * TypeScript port of the enforcement-text extractors (scripts/enrichment/enforcement_actions/extract.py) and the helpers
 * the DOJ and SEC builders share (build_common.clip / money_label / amount_bucket, links.Companies), so scheduled runs
 * build DOJ press-release and SEC litigation-release rows exactly as build_doj.py / build_sec.py do.
 *
 * Python semantics are kept where they change results: regular expressions follow Python `re` (Unicode \w \s \d \b,
 * `.` never matching a newline, `$` before a final newline, a case-sensitive island inside a case-insensitive pattern
 * written out explicitly); html.unescape is Python's (pyHtml.ts); every offset and length is counted in code points;
 * round(x, 2) and the `{:,.2f}` formats round the exact binary value half to even. Tested equal to the Python functions
 * on real DOJ and SEC releases (enforcementText.test.ts, fixtures generated by scripts/api_law/enforcement/goldens.py).
 */
import { PY_WS, pyStrip } from "../py.ts";
import { htmlUnescape } from "./pyHtml.ts";

/* ------------------------------------------------------------------ Python regex and string helpers */

const WORD_CHARS = "\\p{L}\\p{N}_";
const WB = `(?:(?<=[${WORD_CHARS}])(?![${WORD_CHARS}])|(?<![${WORD_CHARS}])(?=[${WORD_CHARS}]))`;
const NWB = `(?:(?<=[${WORD_CHARS}])(?=[${WORD_CHARS}])|(?<![${WORD_CHARS}])(?![${WORD_CHARS}]))`;

/**
 * Translate a Python `re` pattern (str, no VERBOSE) to a JavaScript source for the `u` flag: Unicode \s \w \d \b,
 * `.` never matching a newline, `$` also before a final newline, `(?P<name>` groups, literal braces escaped, and any
 * escaped punctuation read as itself. Escapes are tracked so a class ending in an escaped bracket stays one class.
 */
export function pyToJs(pattern: string): string {
  const p = pattern.replace(/\(\?P</g, "(?<");
  let out = "";
  let inClass = false;
  let classStart = false;
  for (let i = 0; i < p.length; i++) {
    const c = p[i]!;
    const atStart = classStart;
    classStart = false;
    if (c === "\\") {
      const n = p[i + 1];
      if (n === undefined) throw new Error("trailing backslash");
      i++;
      if (n === "s") out += inClass ? PY_WS : `[${PY_WS}]`;
      else if (n === "S") {
        if (inClass) throw new Error("\\S inside a class is not supported");
        out += `[^${PY_WS}]`;
      } else if (n === "w") out += inClass ? WORD_CHARS : `[${WORD_CHARS}]`;
      else if (n === "W") {
        if (inClass) throw new Error("\\W inside a class is not supported");
        out += `[^${WORD_CHARS}]`;
      } else if (n === "d") out += "\\p{Nd}";
      else if (n === "D") {
        if (inClass) throw new Error("\\D inside a class is not supported");
        out += "\\P{Nd}";
      } else if (n === "b" && !inClass) out += WB;
      else if (n === "B" && !inClass) out += NWB;
      else if (/[A-Za-z0-9]/.test(n)) {
        if ("tnrfvxu".includes(n) || (/[1-9]/.test(n) && !inClass)) out += "\\" + n;
        else throw new Error(`unsupported escape \\${n}`);
      } else if ("^$\\.*+?()[]{}|/-".includes(n)) out += "\\" + n;
      else out += n;
      continue;
    }
    if (inClass) {
      if (c === "]" && !atStart) inClass = false;
      out += c === "]" && atStart ? "\\]" : c;
      continue;
    }
    if (c === "[") {
      inClass = true;
      out += c;
      if (p[i + 1] === "^") {
        out += "^";
        i++;
      }
      classStart = true;
      continue;
    }
    if (c === ".") out += "[^\\n]";
    else if (c === "$") out += "(?=\\n?$)";
    else if (c === "{" && !/^\{\d+(,\d*)?\}/.test(p.slice(i))) out += "\\{";
    else if (c === "}" && !/\{\d+(,\d*)?$/.test(p.slice(0, i))) out += "\\}";
    else out += c;
  }
  return out;
}

/** A RegExp with Python `re` semantics (flags: i, s, g). */
export function rx(pattern: string, flags = ""): RegExp {
  const src = pyToJs(pattern);
  // re.S: `.` matches a newline too
  return new RegExp(flags.includes("s") ? src.replaceAll("[^\\n]", "[\\s\\S]") : src, "u" + flags);
}

/** A case-insensitive word for a pattern compiled without the i flag (Python re.I also folds K and ſ). */
export function ci(word: string): string {
  return Array.from(word)
    .map((c) => {
      const lo = c.toLowerCase();
      const up = c.toUpperCase();
      if (lo === up) return c === "-" || c === "." ? `\\${c}` : c;
      const extra = lo === "k" ? "\u212a" : lo === "s" ? "\u017f" : "";
      return `[${lo}${up}${extra}]`;
    })
    .join("");
}

const hasSurrogates = (s: string) => /[\ud800-\udfff]/.test(s);
/** len(s) */
export const cpLen = (s: string) => (hasSurrogates(s) ? Array.from(s).length : s.length);
/** Code-point index of a code-unit index of s. */
export function cpIndex(s: string, unit: number): number {
  if (!hasSurrogates(s)) return unit;
  return Array.from(s.slice(0, unit)).length;
}
/** s[a:b] in code points (b may be omitted). */
function cpSlice(s: string, a: number, b?: number): string {
  if (!hasSurrogates(s)) return s.slice(a, b);
  return Array.from(s).slice(a, b).join("");
}
/** text[unit:unit+n] counted in code points from a code-unit index. */
function after(text: string, unit: number, n: number): string {
  const rest = text.slice(unit);
  return hasSurrogates(rest) ? Array.from(rest).slice(0, n).join("") : rest.slice(0, n);
}
/** text[max(0, unit-n):unit] counted in code points back from a code-unit index. */
function before(text: string, unit: number, n: number): string {
  const head = text.slice(0, unit);
  if (!hasSurrogates(head)) return head.slice(Math.max(0, head.length - n));
  const cps = Array.from(head);
  return cps.slice(Math.max(0, cps.length - n)).join("");
}
const rstrip = (s: string) => s.replace(new RegExp(`[${PY_WS}]+$`, "u"), "");

function* finditer(re: RegExp, s: string): Generator<RegExpExecArray> {
  const g = new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g");
  let m: RegExpExecArray | null;
  while ((m = g.exec(s))) {
    yield m;
    if (m[0] === "") g.lastIndex++;
  }
}
function search(re: RegExp, s: string): RegExpExecArray | null {
  return new RegExp(re.source, re.flags.replace(/[gy]/g, "")).exec(s);
}
function match(re: RegExp, s: string): RegExpExecArray | null {
  const r = new RegExp(re.source, re.flags.replace(/[gy]/g, "") + "y");
  return r.exec(s);
}
function fullmatch(re: RegExp, s: string): RegExpExecArray | null {
  const r = new RegExp(`(?:${re.source})(?![\\s\\S])`, re.flags.replace(/[gy]/g, "") + "y");
  return r.exec(s);
}
function sub(re: RegExp, repl: string, s: string): string {
  return s.replace(new RegExp(re.source, re.flags.includes("g") ? re.flags : re.flags + "g"), () => repl);
}

/** The exact decimal expansion of a finite double (|x| < 1e21), as a digit string with a point. */
function exactDecimal(x: number): string {
  return Math.abs(x).toFixed(100).replace(/0+$/, "").replace(/\.$/, ".0");
}
/** Round the exact value of x to `places` decimals, ties to even (Python round(x, n) / format). Returns the digits. */
export function pyRoundStr(x: number, places: number): string {
  const neg = x < 0;
  const [ip, fp = ""] = exactDecimal(x).split(".");
  const keep = (fp + "0".repeat(places + 1)).slice(0, places);
  const restDigits = fp.slice(places);
  let digits = ip! + keep;
  const first = restDigits[0] ?? "0";
  const tail = restDigits.slice(1).replace(/0/g, "");
  const last = Number(digits[digits.length - 1] ?? "0");
  const up = first > "5" || (first === "5" && (tail.length > 0 || last % 2 === 1));
  if (up) {
    const arr = digits.split("").map(Number);
    let i = arr.length - 1;
    for (; i >= 0; i--) {
      if (arr[i]! < 9) {
        arr[i]!++;
        break;
      }
      arr[i] = 0;
    }
    if (i < 0) arr.unshift(1);
    digits = arr.join("");
  }
  const intPart = places ? digits.slice(0, digits.length - places) || "0" : digits;
  const frac = places ? digits.slice(digits.length - places) : "";
  const s = places ? `${intPart.replace(/^0+(?=\d)/, "")}.${frac}` : intPart.replace(/^0+(?=\d)/, "");
  return (neg && /[1-9]/.test(s) ? "-" : "") + s;
}
/** round(x, n) */
export const pyRoundTo = (x: number, places: number) => Number(pyRoundStr(x, places));
const group = (intDigits: string) => intDigits.replace(/\B(?=(\d{3})+(?!\d))/g, ",");
/** f"{x:,.{n}f}" */
export function pyFormatGrouped(x: number, places: number): string {
  const s = pyRoundStr(x, places);
  const neg = s.startsWith("-");
  const [ip, fp] = (neg ? s.slice(1) : s).split(".");
  return (neg ? "-" : "") + group(ip!) + (places ? `.${fp}` : "");
}

/* ------------------------------------------------------------------ text */

const TAG = rx("<[^>]+>", "g");
const WS = rx("[ \\t\\r\\f\\v]+", "g");
const BLOCK = rx("</(?:p|div|h[1-6]|li|tr|table|blockquote|ul|ol)>|<br\\s*/?>", "gi");
const COMMENT = rx("<!--.*?-->", "gs");
const SCRIPT = rx("<(script|style)\\b.*?</\\1>", "gsi");
const COMMENT_MARK = rx("<!--|-->", "g");

/** extract.html_to_text */
export function htmlToText(fragment: string | null | undefined): string {
  if (!fragment) return "";
  let text = sub(COMMENT, " ", fragment);
  text = sub(SCRIPT, " ", text);
  text = sub(COMMENT_MARK, " ", text);
  text = sub(BLOCK, "\n", text);
  text = sub(TAG, " ", text);
  text = htmlUnescape(text).replaceAll("\xa0", " ").replaceAll("\u200b", "");
  const lines = text.split("\n").map((line) => pyStrip(sub(WS, " ", line)));
  return lines.filter((l) => l).join("\n");
}

/** the builders' title cleaning: tags removed, entities decoded, whitespace runs collapsed, stripped */
export function cleanTitle(title: string | null | undefined): string {
  return pyStrip(sub(rx("\\s+"), " ", htmlUnescape(sub(TAG, " ", title ?? ""))));
}

