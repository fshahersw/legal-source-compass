const ABBREV = new Set(
  "u.s inc corp co ltd no nos mr mrs ms dr jr sr st v vs gen atty sen rep gov lt sgt capt col maj jan feb mar apr jun jul aug sep sept oct nov dec a.m p.m l.l.c llc n.a s.a u.s.c c.f.r d.c ave blvd fla cal calif tex ill pa va mass mich minn wis wash ariz colo conn del ga ky la md mo mont neb nev okla or tenn dist ct cir e.g i.e etc approx dept est fig jud u.s.a n.y n.j s.d n.d e.d w.d m.d c.d sec secs par para ch art supp f op jd esq hon prof rev messrs pp".split(
    " ",
  ),
);
const BOUNDARY = rx("[.!?][\"”’)\\]]*\\s+(?=[\"“(\\[]?[A-Z0-9])", "g");
const TOKEN = rx("([A-Za-z.]+)\\.$");

export type Span = [number, number];

/** extract.sentence_spans (code-unit offsets internally) */
export function sentenceSpans(text: string): Span[] {
  const spans: Span[] = [];
  for (const line of finditer(rx("[^\\n]+", "g"), text)) {
    const seg = line[0];
    const base = line.index;
    let start = 0;
    for (const m of finditer(BOUNDARY, seg)) {
      const prior = seg.slice(start, m.index + 1);
      const token = search(TOKEN, prior);
      const word = token ? token[1]!.toLowerCase().replace(/\.+$/, "") : "";
      if (word && (ABBREV.has(word) || fullmatch(rx("[a-z]"), word) || fullmatch(rx("(?:[a-z]\\.)+[a-z]"), word))) continue;
      spans.push([base + start, base + m.index + 1 + rstrip(m[0].slice(1)).length]);
      start = m.index + m[0].length;
    }
    spans.push([base + start, base + seg.length]);
  }
  return spans.filter(([a, b]) => b > a);
}

/** extract.sentence_at: the sentence containing code-unit offset pos (a window of `limit` code points when long) */
export function sentenceAt(text: string, pos: number, spans?: Span[], limit = 400): string | null {
  for (const [a, b] of spans ?? sentenceSpans(text)) {
    if (a <= pos && pos < b) {
      const s = pyStrip(text.slice(a, b));
      if (cpLen(s) <= limit) return s;
      const seg = Array.from(text.slice(a, b));
      const rel = Array.from(text.slice(a, pos)).length;
      const lo = Math.max(0, rel - Math.floor(limit / 2));
      const hi = Math.min(seg.length, lo + limit);
      let w = seg.slice(lo, hi);
      if (lo > 0 && w.slice(0, 40).includes(" ")) w = w.slice(w.indexOf(" ") + 1);
      if (hi < seg.length && w.slice(-40).includes(" ")) w = w.slice(0, w.lastIndexOf(" "));
      return pyStrip(w.join(""));
    }
  }
  return null;
}

