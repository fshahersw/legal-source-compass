/** extract.amount_value */
export function amountValue(num: string, mult: string | undefined): number | null {
  const n = Number(num.replaceAll(",", ""));
  if (!Number.isFinite(n)) return null;
  const v = mult ? n * MULT[mult.trim().toLowerCase()]! : n;
  return pyRoundTo(v, 2);
}

function reading(m: RegExpExecArray, text: string): { value: number | null; ranged: boolean; ambiguous: boolean } {
  const g = m.groups ?? {};
  const mult = g["mult"] ?? g["abbr"];
  const value = amountValue(g["num"]!, mult);
  const end = m.index + m[0].length;
  const ranged = !mult && match(RANGE_AFTER, after(text, end, 40)) !== null;
  const ambiguous =
    (Boolean(mult) && Number(g["num"]!.replaceAll(",", "")) >= 1000) ||
    (!mult && match(FOREIGN_MULT_AFTER, after(text, end, 20)) !== null);
  return { value, ranged, ambiguous };
}

export type Amount = {
  as_written: string;
  offset: number;
  value_usd?: number;
  range_start?: true;
  ambiguous_as_written?: true;
  sentence?: string;
  keyword?: string;
  boilerplate?: true;
  /** code-unit offset (not part of the Python output) */
  _unit?: number;
};

/** extract.extract_amounts (offsets in code points; `_unit` keeps the code-unit offset for span checks) */
export function extractAmounts(text: string, spans?: Span[], limit?: number): Amount[] {
  const sp = spans ?? sentenceSpans(text);
  const out: Amount[] = [];
  for (const m of finditer(AMOUNT, text)) {
    const { value, ranged, ambiguous } = reading(m, text);
    const sentence = sentenceAt(text, m.index, sp);
    let kind: string | null = null;
    if (sentence) {
      const probe = sub(NOT_KEYWORDS, " ", sentence);
      for (const [name, pattern] of KIND_KEYWORDS)
        if (search(pattern, probe)) {
          kind = name;
          break;
        }
    }
    const end = m.index + m[0].length;
    if (match(SPECIAL_AFTER, after(text, end, 50)) || search(SPECIAL_BEFORE, before(text, m.index, 50)))
      kind = "special assessment";
    else if (match(TRANSACTION_AFTER, after(text, end, 60))) kind = "transaction value";
    else if (kind && RESOLUTION_KINDS.has(kind) && sentence && search(CUMULATIVE_SPAN, sentence) && search(CUMULATIVE_VERB, sentence))
      kind = "cumulative total";
    const a: Amount = { as_written: m[0], offset: cpIndex(text, m.index) };
    const v = ranged || ambiguous ? null : value;
    if (v !== null) a.value_usd = v;
    if (ranged) a.range_start = true;
    if (ambiguous) a.ambiguous_as_written = true;
    if (sentence !== null) a.sentence = sentence;
    if (kind !== null) a.keyword = kind;
    Object.defineProperty(a, "_unit", { value: m.index, enumerable: false });
    out.push(a);
    if (limit && out.length >= limit) break;
  }
  return out;
}

