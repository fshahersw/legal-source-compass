export type Court = { as_written: string; offset: number; court_id?: string; _unit?: number };

/** extract.extract_courts */
export function extractCourts(text: string, limit?: number): Court[] {
  const out: (Court & { _cid: string | null })[] = [];
  const seen = new Set<string>();
  const push = (m: RegExpExecArray, cid: string | null) => {
    const key = JSON.stringify([m[0], cid]);
    if (seen.has(key)) return;
    seen.add(key);
    out.push(withUnit({ as_written: m[0], offset: cpIndex(text, m.index), _cid: cid }, m.index));
  };
  for (const m of finditer(DISTRICT_COURT, text)) push(m, districtId(m.groups!["div"], m.groups!["state"]!));
  for (const m of finditer(APPEALS, text)) push(m, CIRCUITS[m.groups!["cir"]!]!);
  for (const [pattern, cid] of SPECIAL) for (const m of finditer(pattern, text)) push(m, cid);
  out.sort((a, b) => a.offset - b.offset);
  const clean = out.map((c) => {
    const o: Court = { as_written: c.as_written, offset: c.offset };
    if (c._cid !== null) o.court_id = c._cid;
    return withUnit(o, (c as { _unit?: number })._unit ?? 0);
  });
  return limit ? clean.slice(0, limit) : clean;
}

