export const NOT_RECORDED = "Not recorded";

/** build_common.money_label */
export function moneyLabel(value: number | null | undefined): string {
  if (value === null || value === undefined) return NOT_RECORDED;
  const v = value;
  if (v >= 1e9) return `$${pyFormatGrouped(v / 1e9, 2)} billion`;
  if (v >= 1e6) return `$${pyFormatGrouped(v / 1e6, 2)} million`;
  return Number.isInteger(v) ? `$${pyFormatGrouped(v, 0)}` : `$${pyFormatGrouped(v, 2)}`;
}

/** build_common.amount_bucket */
export function amountBucket(value: number | null | undefined): string {
  if (value === null || value === undefined) return "none";
  if (value >= 1e9) return "1b_plus";
  if (value >= 1e8) return "100m_plus";
  if (value >= 1e7) return "10m_plus";
  if (value >= 1e6) return "1m_plus";
  return "under_1m";
}

/** build_common.clip: first `limit` code points cut at a word boundary; [excerpt, truncated] */
export function clip(text: string | null | undefined, limit: number): [string | null, boolean] {
  if (text === null || text === undefined) return [null, false];
  if (cpLen(text) <= limit) return [text, false];
  let cut = cpSlice(text, 0, limit);
  const cps = Array.from(cut);
  const space = cps.lastIndexOf(" ");
  if (space > limit * 0.8) cut = cps.slice(0, space).join("");
  return [rstrip(cut), true];
}

/** build_common.facts_list: lists joined by "; ", empty values as Not recorded, everything as str() */
export function factsList(pairs: [string, unknown][]): [string, string][] {
  return pairs.map(([label, value]) => {
    let v: unknown = value;
    if (Array.isArray(v)) v = v.filter((x) => x !== null && x !== undefined && x !== "").map(pyStr).join("; ") || null;
    return [label, v === null || v === undefined || v === "" ? NOT_RECORDED : pyStr(v)];
  });
}

/** Python str() of a JSON scalar (floats keep their ".0") */
export function pyStr(v: unknown): string {
  if (v === true) return "True";
  if (v === false) return "False";
  if (v === null || v === undefined) return "None";
  return String(v);
}

/** links.Companies over the saved company_sec_profiles lookup ([cik, title] pairs). */
export class Companies {
  readonly unique = new Map<string, string>();
  readonly ambiguous = new Set<string>();
  readonly names = new Map<string, string>();
  constructor(rows: [string, string][]) {
    const keys = new Map<string, Set<string>>();
    for (const [cik, title] of rows) {
      if (!/^\d+$/.test(cik)) continue;
      this.names.set(cik, title);
      const key = normalizeCompany(title);
      if (key) keys.set(key, (keys.get(key) ?? new Set()).add(cik));
    }
    for (const [k, v] of keys) if (v.size === 1) this.unique.set(k, [...v][0]!);
    else this.ambiguous.add(k);
  }
  match(name: string): { cik: string; registrant: string; method: string; key: string } | null {
    const key = normalizeCompany(name);
    if (!key || this.ambiguous.has(key)) return null;
    const cik = this.unique.get(key);
    if (!cik) return null;
    return { cik, registrant: this.names.get(cik)!, method: "exact normalised name equality", key };
  }
}
